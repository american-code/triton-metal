    private static let floatPredicates: [String: String] = [
        "oeq": "==", "one": "!=", "olt": "<", "ole": "<=", "ogt": ">", "oge": ">=",
        "ueq": "==", "une": "!=", "ult": "<", "ule": "<=", "ugt": ">", "uge": ">=",
