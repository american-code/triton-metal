import Foundation

/// Describes one kernel argument as it is bound at launch time. The argument's
/// position in `tt.func` is also its Metal buffer index.
public struct KernelArgument: Sendable, Equatable {
    public enum Kind: String, Sendable {
        /// `!tt.ptr<T>` — bound to an `MTLBuffer` in the `device` address space.
        case pointer
        /// A scalar kernel parameter — bound with `setBytes` as `constant T&`.
        case scalar
    }

    public var index: Int
    public var kind: Kind
    /// Triton spelling of the (pointee) element type, e.g. `f32`, `i32`.
    public var dtype: String
}

/// Everything the launcher needs to run an emitted kernel.
public struct EmittedKernel: Sendable, Equatable {
    public var name: String
    /// Block size per dimension (Triton's `BLOCK_SIZE`, `BLOCK_M`/`BLOCK_N`, ...).
    /// Empty for a kernel with no tensors at all.
    public var blockShape: [Int]
    /// Total elements in the block — the product of `blockShape`.
    public var blockSize: Int
    /// A multiple of the 32-wide simdgroup, capped by Metal's 1024-thread limit.
    /// Threads stride over the block's innermost dimension.
    public var threadsPerThreadgroup: Int
    public var arguments: [KernelArgument]
}

public struct EmissionResult: Sendable {
    public var source: String
    public var kernels: [EmittedKernel]
}

/// Lowers a parsed Triton module to Metal Shading Language.
///
/// Execution model: one Metal threadgroup per Triton program. Tensors live in a
/// block index space of rank R (see `BlockLayout`), walked by R nested loops:
/// the innermost dimension is distributed over the threadgroup's threads, outer
/// dimensions are iterated uniformly by every thread. A value is emitted at the
/// shallowest loop depth its own dimensions (and its operands) allow, so
/// program-uniform work stays in the prologue and row-uniform work stays out of
/// the innermost loop.
enum MSLEmitter {
    static let preamble = """
        // Generated by triton-metal (TritonMetalCore). Do not edit.
        //
        // Execution model: one threadgroup per Triton program. A kernel's tensors
        // share one block index space; the innermost block dimension is strided
        // across the threadgroup's threads, outer dimensions are looped uniformly.
        #include <metal_stdlib>
        using namespace metal;
        """

    /// Metal's standard library has no `erf`. Emitted only when a kernel needs it.
    static let erfHelper = """
        // math.erf: Abramowitz & Stegun 7.1.26. Metal has no erf() of its own; this
        // approximation is accurate to ~1.5e-7 absolute, which is float precision
        // over erf's [-1, 1] range.
        template <typename T> inline T tm_erf(T x) {
            T sign = x < T(0) ? T(-1) : T(1);
            T a = fabs(x);
            T t = T(1) / (T(1) + T(0.3275911) * a);
            T poly = t * (T(0.254829592) + t * (T(-0.284496736) + t * (T(1.421413741)
                   + t * (T(-1.453152027) + t * T(1.061405429)))));
            return sign * (T(1) - poly * precise::exp(-a * a));
        }
        """

    /// Metal has no float `atomic_fetch_max_explicit`/`min`. Verified on an M1 Pro
    /// (Metal 3, macOS 26.5): the templates exist but `_valid_fetch_max_type` is
    /// not satisfied for `device float *`, so the call does not resolve, while
    /// `atomic_fetch_add_explicit` on `atomic_float` compiles and runs. Float
    /// max/min therefore go through a compare-exchange loop on the bit pattern.
    ///
    /// Cost, honestly: one extra `atomic_load` before the loop, and one retry per
    /// thread that loses a race on the same address. The uncontended path is a
    /// load plus one CAS — about twice a native fetch-max — and contention on a
    /// hot address degrades linearly in the number of contending threads, where a
    /// native fetch-max degrades in whatever the hardware does. Emitted only when
    /// a kernel actually asks for a float max or min.
    static let atomicFloatMinMaxHelper = """
        // tt.atomic_rmw max/min on f32. Metal has no float atomic_fetch_max_explicit
        // (see docs/ARCHITECTURE.md §Atomics), so this is a compare-exchange loop
        // over the bit pattern. Returns the old value, as tt.atomic_rmw must.
        // NaN never wins the comparison, so a NaN already in memory is left alone
        // and a NaN operand is dropped.
        inline float tm_atomic_fmax(device float *p, float v) {
            device atomic_uint *a = (device atomic_uint *)p;
            uint expected = atomic_load_explicit(a, memory_order_relaxed);
            while (as_type<float>(expected) < v) {
                if (atomic_compare_exchange_weak_explicit(
                        a, &expected, as_type<uint>(v),
                        memory_order_relaxed, memory_order_relaxed)) {
                    break;
                }
            }
            return as_type<float>(expected);
        }
        inline float tm_atomic_fmin(device float *p, float v) {
            device atomic_uint *a = (device atomic_uint *)p;
            uint expected = atomic_load_explicit(a, memory_order_relaxed);
            while (v < as_type<float>(expected)) {
                if (atomic_compare_exchange_weak_explicit(
                        a, &expected, as_type<uint>(v),
                        memory_order_relaxed, memory_order_relaxed)) {
                    break;
                }
            }
            return as_type<float>(expected);
        }
        """

    /// `tt.atomic_cas` is a *strong* compare-and-swap: it fails only because the
    /// value differed. MSL provides `atomic_compare_exchange_weak_explicit` alone,
    /// which may also fail spuriously, so the strong one is a loop that retries
    /// exactly when the observed value still equals the comparand. The float
    /// overload compares bit patterns so that a NaN comparand behaves like every
    /// other bit pattern rather than never matching.
    static let atomicCASHelper = """
        // tt.atomic_cas. Metal has only the weak compare-exchange, so a spurious
        // failure (observed value still == cmp) retries; a real failure returns
        // the value that was there. Returns the old value either way.
        inline int tm_atomic_cas(device int *p, int cmp, int val) {
            device atomic_int *a = (device atomic_int *)p;
            int old = cmp;
            while (!atomic_compare_exchange_weak_explicit(
                       a, &old, val, memory_order_relaxed, memory_order_relaxed)) {
                if (old != cmp) { return old; }
                old = cmp;
            }
            return old;
        }
        inline float tm_atomic_cas(device float *p, float cmp, float val) {
            device atomic_float *a = (device atomic_float *)p;
            float old = cmp;
            while (!atomic_compare_exchange_weak_explicit(
                       a, &old, val, memory_order_relaxed, memory_order_relaxed)) {
                if (as_type<uint>(old) != as_type<uint>(cmp)) { return old; }
                old = cmp;
            }
            return old;
        }
        """

    private static func usesErf(_ body: [Instruction]) -> Bool {
        body.contains { instruction in
            switch instruction.kind {
            case .unary(_, .erf, _): return true
            case .forLoop(let loop): return usesErf(loop.body)
            case .ifOp(let branch): return usesErf(branch.thenBody) || usesErf(branch.elseBody)
            default: return false
            }
        }
    }

    static func emit(module: TritonModule, options: MetalCompiler.Options) throws -> EmissionResult {
        var kernels: [EmittedKernel] = []
        var bodies: [String] = []
        var seen: Set<String> = []
        // Whether the float min/max helper is needed is only known once a kernel
        // has been lowered far enough to type its atomic's pointee, so the
        // helpers are composed after the kernels rather than before them.
        var needsFloatAtomicMinMax = false
        var needsAtomicCAS = false

        for function in module.functions {
            guard seen.insert(function.name).inserted else {
                throw CoreError.lowering("duplicate kernel name '\(function.name)'", function.loc)
            }
            let layout = try LayoutInference.compute(for: function)
            var emitter = FunctionEmitter(function: function, options: options, layout: layout)
            let (source, kernel) = try emitter.run()
            needsFloatAtomicMinMax = needsFloatAtomicMinMax || emitter.usesFloatAtomicMinMax
            needsAtomicCAS = needsAtomicCAS || emitter.usesAtomicCAS
            bodies.append(source)
            kernels.append(kernel)
        }

        var chunks: [String] = [preamble]
        if module.functions.contains(where: { usesErf($0.body) }) {
            chunks.append(erfHelper)
        }
        if needsFloatAtomicMinMax { chunks.append(atomicFloatMinMaxHelper) }
        if needsAtomicCAS { chunks.append(atomicCASHelper) }
        chunks.append(contentsOf: bodies)

        return EmissionResult(source: chunks.joined(separator: "\n\n") + "\n", kernels: kernels)
    }
}

// MARK: - Statement tree

/// Emitted MSL, kept as a tree so that loops can still be opened, closed and
/// reopened while lowering (a `tt.reduce` closes the innermost lane loop).
indirect enum Stmt {
    case line(String)
    case group(open: String, body: [Stmt], close: String)

    func render(indent: Int, into lines: inout [String]) {
        let padding = String(repeating: " ", count: indent)
        switch self {
        case .line(let text):
            lines.append(padding + text)
        case .group(let open, let body, let close):
            lines.append(padding + open)
            for statement in body { statement.render(indent: indent + 4, into: &lines) }
            lines.append(padding + close)
        }
    }
}

private struct Frame {
    enum Kind {
        /// The kernel body itself.
        case function
        /// One of the block-dimension loops.
        case laneLoop
        /// An `scf.for`/`scf.if` region lowered per lane, inside the block loops.
        case region
        /// An `scf.for` region hoisted to a threadgroup-uniform level because it
        /// contains a `tt.dot` (whose barriers every thread must reach).
        case uniformRegion
        /// A loop or guard built by a `tt.dot`'s operand staging.
        case staging
    }

    var statements: [Stmt] = []
    /// The block axes whose loops are open around this frame, outermost first.
    var path: [Int]
    var kind: Kind
    var open: String = ""
    var close: String = "}"
    /// True while everything in the frame is a pure definition already recorded in
    /// `history`. Such a frame can be dropped when its loop closes, because any
    /// later use reopens the level and replays the history.
    var discardable: Bool = true
}

/// Where an `scf.yield` writes one of its values.
private enum YieldTarget {
    /// An ordinary carried variable.
    case variable(String)
    /// A `tt.dot` accumulator living in this threadgroup tile; the dot already
    /// updated it in place, so the yield is a no-op that only has to be checked.
    case tile(String)
    /// A per-lane tensor spilled into a threadgroup tile for the duration of a
    /// cross-lane loop. The new value went into `shadow` where it was defined
    /// (the old one is still being read at that point); the copy back happens
    /// once, at the end of the body. See `emitUniformLoop`.
    case spilled(tile: Tile, shadow: Tile, value: String)
    /// A contraction-space value rebuilt from the induction variable instead of
    /// being carried (see `strengthReduce`). Nothing to assign.
    case deferred
}

/// A tensor value staged into threadgroup memory instead of per-lane registers —
/// the second SSA value class `tt.dot` needs.
///
/// `simdgroup_load`/`simdgroup_store` move 8x8 fragments between threadgroup
/// memory and the opaque per-simdgroup matrix registers, so every operand and the
/// accumulator pass through a tile. Tiles are padded up to whole 8x8 fragments and
/// the padding is zero-filled, which is what makes block sizes that are not
/// multiples of 8 work without a separate edge-tile code path.
private struct Tile {
    var name: String
    var element: TMType
    var rows: Int
    var columns: Int
    var paddedRows: Int
    var paddedColumns: Int
    /// Elements of slack after every row.
    ///
    /// Threadgroup memory is banked, and a leading dimension that is a multiple
    /// of the bank count makes a column of a tile land in one bank — which is
    /// exactly what a `simdgroup_load` of a fragment walks. A few elements of
    /// slack per row skews the rows across the banks instead.
    var rowPadding: Int = 0
    /// Block dimensions the two tile dimensions correspond to.
    var rowAxis: Int
    var columnAxis: Int
    /// False for a tile that stands in for a rank-1 value — a spilled `m_i` or
    /// `l_i` — which is one element per row and indexed by the row axis alone.
    var hasColumns: Bool = true

    /// The distance between one row and the next, which is also the leading
    /// dimension every `simdgroup_load` and `simdgroup_store` is given.
    var stride: Int { paddedColumns + rowPadding }
    var elementCount: Int { paddedRows * stride }
    var needsPadding: Bool { paddedRows != rows || paddedColumns != columns }

    /// The block axes a reader of this tile must have loops open for. A tile
    /// dimension of extent 1 is a broadcast and needs none.
    var axes: [Int] {
        var result: [Int] = []
        if rows > 1 { result.append(rowAxis) }
        if hasColumns, columns > 1 { result.append(columnAxis) }
        return result
    }

    /// The slot the staging loops write, always in terms of *their* loop
    /// variables — which walk the fragment padding as well, where `expression`'s
    /// broadcast shortcut would fold every padding lane onto slot zero.
    var slot: String {
        hasColumns
            ? "\(name)[tm_i\(rowAxis) * \(stride)u + tm_i\(columnAxis)]"
            : "\(name)[tm_i\(rowAxis)]"
    }

    /// How the tile reads as an ordinary per-lane value, once the emitter is back
    /// inside the block loops.
    var expression: String {
        let row = rows > 1 ? "tm_i\(rowAxis)" : "0u"
        guard hasColumns else { return "\(name)[\(row)]" }
        let column = columns > 1 ? "tm_i\(columnAxis)" : "0u"
        return "\(name)[\(row) * \(stride)u + \(column)]"
    }
}

// MARK: - Register blocking

/// How one simdgroup's share of a `tt.dot`'s output fragments is grouped.
///
/// A `simdgroup_multiply_accumulate` needs two operand fragments, so handing each
/// simdgroup a single 8x8 output fragment costs two `simdgroup_load`s per unit of
/// arithmetic. Handing it a `tilesM x tilesN` grid instead amortises them: the A
/// fragment staged for a fragment row feeds every output in that row and the B
/// fragment for a column feeds every output in that column, so `tilesM + tilesN`
/// loads feed `tilesM * tilesN` multiply-accumulates. This is the Metal spelling
/// of the register blocking every fast CUDA GEMM does, and it is the first of the
/// three things docs/ARCHITECTURE.md §Matmul throughput named.
private struct RegisterBlocking {
    /// Output fragments per simdgroup, along M and along N.
    var tilesM: Int
    var tilesN: Int
    /// The block grid those carve the output fragments into.
    var blocksM: Int
    var blocksN: Int
    var simdgroups: Int
    /// Passes over the block grid: `ceil(blocks / simdgroups)`.
    var waves: Int

    var blocks: Int { blocksM * blocksN }
    /// True when the last wave does not fill every simdgroup, so its writes need
    /// a guard and its reads a clamp.
    var ragged: Bool { blocks % simdgroups != 0 }
    var fragmentsPerSimdgroup: Int { waves * tilesM * tilesN }

    var summary: String {
        "\(blocksM)x\(blocksN) blocks of \(tilesM)x\(tilesN) fragments over \(simdgroups) "
            + "simdgroup\(simdgroups == 1 ? "" : "s")"
            + (waves == 1 ? "" : ", \(waves) waves")
    }
}

/// The registers one simdgroup holds a `tt.dot` accumulator in, and where in the
/// accumulator tile they came from.
///
/// The fragments are *named* rather than kept in an array: a `simdgroup_float8x8`
/// indexed by a loop variable would be forced to thread memory, which is the one
/// thing this is trying to avoid. Both the wave count and the blocking factors
/// are compile-time constants (the simdgroup count is the reported
/// `threads_per_threadgroup`, which a `tt.dot` kernel's launcher already has to
/// honour), so the emitter can spell every fragment out.
private struct AccumulatorRegisters {
    var tile: Tile
    var blocking: RegisterBlocking
    /// `simdgroup_float8x8` or `simdgroup_half8x8`.
    var matrix: String
    var prefix: String

    /// True when every wave's fragment block sits in the *same* column of the
    /// block grid, so the B fragment a step loads is wave-independent and can be
    /// loaded once instead of once per wave (see `loadAccumulator`).
    var sharedColumns: Bool = false

    func rowBlock(_ wave: Int) -> String { "\(prefix)_bm\(wave)" }
    func columnBlock(_ wave: Int) -> String {
        sharedColumns ? "\(prefix)_bn" : "\(prefix)_bn\(wave)"
    }

    /// A zero-filled fragment, for an accumulator seeded with `dense<0.0>` — it
    /// never has to exist in threadgroup memory at all.
    var zeroFragment: String {
        matrix == "simdgroup_half8x8"
            ? "make_filled_simdgroup_matrix<half, 8, 8>(0.0h)"
            : "make_filled_simdgroup_matrix<float, 8, 8>(0.0f)"
    }
    func live(_ wave: Int) -> String { "\(prefix)_live\(wave)" }
    func register(_ wave: Int, _ row: Int, _ column: Int) -> String {
        "\(prefix)_\(wave)_\(row)_\(column)"
    }

    /// The fragment coordinate of one register, as an MSL expression.
    func fragmentRow(_ wave: Int, _ row: Int) -> String {
        blocking.tilesM == 1
            ? rowBlock(wave) : "(\(rowBlock(wave)) * \(blocking.tilesM)u + \(row)u)"
    }
    func fragmentColumn(_ wave: Int, _ column: Int) -> String {
        blocking.tilesN == 1
            ? columnBlock(wave) : "(\(columnBlock(wave)) * \(blocking.tilesN)u + \(column)u)"
    }
}

// MARK: - Function lowering

private struct FunctionEmitter {
    let function: TritonFunction
    let options: MetalCompiler.Options
    let layout: BlockLayout

    private var types: [String: TMType] = [:]
    private var names: [String: String] = [:]
    /// The loop nest each value is emitted in, outermost axis first.
    private var levels: [String: [Int]] = [:]

    private var frames: [Frame] = []
    private var preamble: [Stmt] = []
    /// Pure definitions, in order, so a reopened loop can recompute them.
    private var history: [(path: [Int], statement: Stmt)] = []
    /// Nests that have been closed once; reopening them needs `history`.
    private var closedLevels: Set<[Int]> = []
    /// Why a nest cannot be recomputed (a store, a region, a reduction epilogue).
    private var notRecomputable: [[Int]: String] = [:]
    /// Where `scf.yield` writes, innermost region last.
    private var yieldTargets: [[YieldTarget]] = []
    /// Shadow-to-carried tile copies the current cross-lane loop body owes at its
    /// end, collected when its `scf.yield` is reached.
    private var spillCopies: [(from: Tile, to: Tile)] = []

    /// Cleared by the first side effect: after a store, nothing may be hoisted
    /// above it.
    private var canHoist = true
    private var usesProgramID = false
    private var usesGridSize = false
    private var usesSimdgroups = false
    private var declaredSimdCount = false
    private var reductionCount = 0
    /// True once a `tt.atomic_rmw max`/`min` on f32 has been lowered, which is
    /// what pulls `tm_atomic_fmax`/`tm_atomic_fmin` into the module.
    private(set) var usesFloatAtomicMinMax = false
    /// True once a `tt.atomic_cas` has been lowered. MSL has only the *weak*
    /// compare-exchange, so the strong one Triton's op means is a small loop.
    private(set) var usesAtomicCAS = false
    /// Every SSA value read by some operation in this function. An atomic that has
    /// to be performed by one thread of a uniform nest can only return a
    /// meaningful old value *to that thread*, so a used result is refused there.
    private let readValues: Set<String>

    // MARK: tt.dot state

    /// Values that live in a threadgroup tile rather than in per-lane registers.
    private var tiles: [String: Tile] = [:]
    /// Accumulator tiles whose 8x8 fragments are held in simdgroup registers for
    /// the whole of an enclosing contraction loop, keyed by tile name. A `tt.dot`
    /// that finds its accumulator here skips the per-step load and store entirely.
    private var residentAccumulators: [String: AccumulatorRegisters] = [:]
    /// While a register-resident accumulator is live, its tile's storage doubles
    /// as the arena its dot's operand tiles are staged in.
    ///
    /// The two never overlap in time: the accumulator's tile is written before the
    /// contraction loop, read straight into registers, and not touched again until
    /// the registers are stored back after the loop — which is exactly the window
    /// in which the operand tiles exist. Sharing the storage is what lets a block
    /// shape whose accumulator alone fills Metal's 32KB budget still have room to
    /// stage its operands, and BLOCK_M x BLOCK_N is the ratio that decides how
    /// many device loads each multiply-accumulate costs.
    private var stagingArena: (name: String, element: TMType, capacity: Int, cursor: Int)?
    /// Operand tiles of the contraction loop currently being emitted that swap
    /// between two arena halves at the end of every step.
    private var pingPongTiles: [(name: String, element: String)] = []
    /// Every instruction seen so far, keyed by the value it defines, so that a
    /// `tt.dot` can rebuild its operands inside its own staging loops.
    private var definitions: [String: Instruction] = [:]
    /// Program order, for replaying a rebuilt subgraph in the order it was written.
    private var valueOrder: [String: Int] = [:]
    private var nextValueOrder = 0
    /// Values that exist only to feed a `tt.dot` and are therefore never emitted
    /// where they appear (see `DotDeferral`).
    private let materialised: Set<String>
    /// Reduction results a `tt.dot`'s staging loops read. A `tt.reduce` is the one
    /// thing `recomputationOrder` cannot rebuild, so these are written into a
    /// small threadgroup array where they are computed and read out of it there.
    private let spilledReductions: Set<String>
    /// Tiles a `tt.dot`'s accumulator must be staged into rather than allocating
    /// one, keyed by the dot's result: the tile a cross-lane loop carries.
    private var boundAccumulators: [String: Tile] = [:]
    /// Where the value yielded into a spilled carried tensor is written, keyed by
    /// the yielded value. Written where it is *defined*, because by the time the
    /// `scf.yield` is reached the nest that computed it is closed.
    private var shadowWrites: [String: Tile] = [:]
    /// One arena every `tt.dot`'s operand tiles are carved out of, for kernels
    /// with more than one dot: two dots' operands are never live at the same time
    /// (a barrier separates them), and FA-2 does not fit otherwise.
    private var sharedArena: (name: String, element: TMType, capacity: Int)?
    private var sharedArenaCursor = 0
    private var sharedArenaDeclared = false
    /// True once any tile is written by ordinary per-lane code, which is what
    /// makes a `tt.dot`'s staging loops need a barrier in front of them.
    private var hasSpilledTiles = false
    /// How many `tt.dot`s this kernel contains, which decides whether their
    /// operand tiles share one arena.
    private let dotTotal: Int
    /// True when some `scf.for` in this kernel is hoisted out of the block loops
    /// to a threadgroup-uniform level, which is what makes closing a loop early
    /// and rebuilding it later the normal case rather than the exception.
    private let hoistsUniformRegions: Bool
    /// Non-zero while rebuilding a subgraph inside a staging loop: statements go
    /// straight into the current frame and nothing is hoisted or remembered.
    private var stagingDepth = 0
    /// Which frame of the staging nest the next rebuilt statement belongs in.
    private var stagingTargetFrame: Int?
    private var tileCount = 0
    private var dotCount = 0
    private var advanceCount = 0
    private var threadgroupBytes = 0

    /// Metal guarantees at least 32KB of threadgroup memory per threadgroup; the
    /// M-series parts expose exactly that much to a compute kernel.
    static let threadgroupMemoryLimit = 32768

    init(function: TritonFunction, options: MetalCompiler.Options, layout: BlockLayout) {
        self.function = function
        self.options = options
        self.layout = layout
        let live = layout.hasDot ? DotDeferral.materialised(in: function) : []
        self.materialised = live
        self.spilledReductions = layout.hasDot
            ? FunctionEmitter.reductionsReadByADot(in: function, layout: layout) : []
        self.dotTotal = FunctionEmitter.countDots(function.body)
        self.readValues = FunctionEmitter.valuesRead(in: function.body)
        self.hoistsUniformRegions = function.body.contains {
            if case .forLoop(let loop) = $0.kind {
                return FunctionEmitter.containsCrossLane(loop.body)
            }
            return false
        }
    }

    /// Every value some operation reads, regions included.
    private static func valuesRead(in body: [Instruction]) -> Set<String> {
        var result: Set<String> = []
        for instruction in body {
            result.formUnion(instruction.kind.operandNames)
            switch instruction.kind {
            case .forLoop(let loop):
                result.formUnion(valuesRead(in: loop.body))
            case .ifOp(let branch):
                result.formUnion(valuesRead(in: branch.thenBody))
                result.formUnion(valuesRead(in: branch.elseBody))
            default:
                continue
            }
        }
        return result
    }

    private var rank: Int { layout.rank }

    /// True for kernels with a `tt.dot`, which changes two policies: the
    /// threadgroup is sized for simdgroup-matrix work rather than for the
    /// innermost block dimension, and values that only feed a dot are deferred.
    private var usesDot: Bool { layout.hasDot }

    /// The nest at which every thread of the threadgroup runs the same
    /// statement — where a `tt.dot`'s barriers have to sit.
    private var uniformLevel: [Int] {
        frames.last { $0.kind == .region || $0.kind == .uniformRegion }?.path ?? []
    }

    /// True when `ssa` is an all-zero splat constant — the seed every Triton
    /// matmul gives its accumulator (`arith.constant dense<0.000000e+00>`).
    ///
    /// Worth detecting on its own because a zero accumulator has no prologue: the
    /// fragments can be filled in registers rather than staged through a tile and
    /// read back out of it (see `loadAccumulator`).
    private func isZeroSplat(_ ssa: String) -> Bool {
        guard let instruction = definitions[ssa],
            case .constant(_, let type, let value) = instruction.kind, type.isTensor
        else { return false }
        switch value {
        case .integer(let v): return v == 0
        case .float(let v): return v == 0
        }
    }

    /// True when the value is only ever read by a `tt.dot`, so it is rebuilt
    /// inside that dot's staging loops instead of being emitted here.
    private func isDeferred(_ ssa: String) -> Bool {
        guard usesDot, stagingDepth == 0, !materialised.contains(ssa) else { return false }
        guard let map = layout.axes[ssa], !map.isEmpty else { return false }
        return true
    }

    // MARK: - Driver

    mutating func run() throws -> (String, EmittedKernel) {
        var arguments: [KernelArgument] = []
        var parameters: [String] = []

        for argument in function.arguments {
            let name = register(argument.name, type: argument.type)
            levels[argument.name] = []
            switch argument.type {
            case .pointer(let pointee):
                if case .tensor = pointee {
                    throw CoreError.unsupportedType(
                        "\(argument.type) (block pointers are not lowered yet)", argument.loc)
                }
                parameters.append(
                    "device \(try scalarTypeName(pointee, argument.loc)) *\(name) "
                        + "[[buffer(\(argument.index))]]")
                arguments.append(
                    KernelArgument(index: argument.index, kind: .pointer, dtype: "\(pointee)"))
            case .integer, .float:
                parameters.append(
                    "constant \(try scalarTypeName(argument.type, argument.loc)) &\(name) "
                        + "[[buffer(\(argument.index))]]")
                arguments.append(
                    KernelArgument(index: argument.index, kind: .scalar, dtype: "\(argument.type)"))
            case .tensor:
                throw CoreError.unsupportedType(
                    "\(argument.type) as a kernel argument", argument.loc)
            }
        }

        frames = [Frame(path: [], kind: .function)]
        for instruction in function.body {
            try emit(instruction)
        }
        try ensureLevel([], function.loc)

        if usesProgramID {
            parameters.append("uint3 tm_program_id [[threadgroup_position_in_grid]]")
        }
        if usesGridSize {
            parameters.append("uint3 tm_grid_size [[threadgroups_per_grid]]")
        }
        // A tt.dot stages its tiles with the whole threadgroup even when every
        // block dimension is a broadcast (a 1x1x1 product still has an 8x8 tile).
        if rank > 0 || usesDot {
            parameters.append("uint3 tm_thread_id [[thread_position_in_threadgroup]]")
            parameters.append("uint3 tm_threadgroup_size [[threads_per_threadgroup]]")
        }
        if usesSimdgroups {
            parameters.append("ushort tm_simd_lane [[thread_index_in_simdgroup]]")
            parameters.append("ushort tm_simd_group [[simdgroup_index_in_threadgroup]]")
        }

        let kernel = EmittedKernel(
            name: function.name,
            blockShape: layout.shape,
            blockSize: layout.shape.reduce(1, *),
            threadsPerThreadgroup: threadsPerThreadgroup,
            arguments: arguments)

        var lines: [String] = []
        let shapeText = layout.shape.isEmpty
            ? "scalar" : "BLOCK=" + layout.shape.map(String.init).joined(separator: "x")
        lines.append(
            "// kernel \(function.name): \(shapeText), "
                + "threadgroup=\(kernel.threadsPerThreadgroup) threads")
        lines.append("kernel void \(function.name)(")
        lines.append(parameters.map { "    " + $0 }.joined(separator: ",\n"))
        lines.append(") {")
        for statement in preamble + frames[0].statements {
            statement.render(indent: 4, into: &lines)
        }
        lines.append("}")
        return (lines.joined(separator: "\n"), kernel)
    }

    /// Threads stride over the innermost block dimension of each nest. Always a
    /// whole number of simdgroups so that `simd_shuffle_down` reductions see 32
    /// live lanes.
    private var threadsPerThreadgroup: Int {
        let requested = max(1, options.numSimdgroups) * 32
        // A tt.dot hands 8x8 output fragments out one per simdgroup and stages its
        // tiles with the whole threadgroup, so clamping to the innermost block
        // dimension — an occupancy heuristic for elementwise kernels — would only
        // starve it, and a simdgroup matrix operation needs 32 live lanes even
        // when every block dimension is a broadcast.
        if usesDot { return min(1024, max(32, (requested + 31) / 32 * 32)) }
        let distributed = (0..<rank).filter { !layout.isUniform($0) }.map { layout.shape[$0] }
        guard let innermost = distributed.max() ?? layout.shape.max() else { return 1 }
        return min(1024, max(32, (max(1, min(innermost, requested)) + 31) / 32 * 32))
    }

    /// True when the per-lane block loops spread the threadgroup over the two
    /// innermost block dimensions rather than over the innermost one alone.
    ///
    /// The innermost-only rule is an occupancy bug for a `tt.dot` kernel's
    /// epilogue: the threadgroup is sized for simdgroup-matrix work (512 threads
    /// at `num_warps=16`) while `BLOCK_N` is typically 64 or 128, so three
    /// quarters of the threads have nothing to do while the other quarter walks
    /// every row of the accumulator tile on its own. Spreading over both
    /// dimensions puts all of them to work and shortens each thread's row walk by
    /// the same factor, while keeping `laneWidth` consecutive threads on
    /// consecutive columns so the device stores stay coalesced.
    ///
    /// Two conditions. Only dot kernels, because only they are contractually
    /// launched at exactly the reported `threads_per_threadgroup` — an
    /// elementwise kernel strides the innermost dimension by the *runtime*
    /// `tm_threadgroup_size.x` precisely so that it does not care. And no
    /// `tt.reduce` anywhere, because a reduction closes the innermost loop and
    /// then folds across the whole threadgroup, which requires every thread to be
    /// in the same row (§Cross-lane regions).
    /// Restricted to rank 2, which is every kernel the two-dimensional split was
    /// measured on: with three block axes a value's nest is over *its* axes
    /// (§Execution model), and which two of them a lane index should be split
    /// across is no longer a property of the kernel.
    private var distributesRows: Bool {
        guard rank >= 2 else { return false }
        // A `tt.reduce` used to force the innermost-only split, because its fold
        // runs across the whole threadgroup and so needs every thread in the same
        // row. Splitting the lane index gives each row a *group* of lanes and the
        // fold runs inside that group instead (`emitReduce`), which is what makes
        // an attention kernel's 2 x BLOCK_M row reductions per iteration parallel
        // rather than a queue of threadgroup barriers.
        if FunctionEmitter.containsReduce(function.body) { return usesDot || rank == 2 }
        return usesDot && rank == 2
    }

    /// How many threads stride the innermost block dimension when the loops
    /// spread over two of them. A power of two that divides the threadgroup, so
    /// that `tid / lanes` and `tid % lanes` between them cover every point of the
    /// two-dimensional index space exactly once.
    ///
    /// A kernel with a reduction caps this at the 32-lane simdgroup, so that the
    /// lanes sharing a row always share a simdgroup and the fold is `simd_shuffle`
    /// with no threadgroup memory and no barrier at all.
    private var laneWidth: Int {
        guard distributesRows else { return threadsPerThreadgroup }
        let reduces = FunctionEmitter.containsReduce(function.body)
        // Every nest splits the same threadgroup the same way, or the shared outer
        // loop could not be shared: take the narrowest innermost extent there is.
        var innermost = layout.shape.last ?? threadsPerThreadgroup
        if rank > 2 || reduces {
            let distributed = (0..<rank).filter { !layout.isUniform($0) }.map { layout.shape[$0] }
            innermost = distributed.min() ?? innermost
        }
        let ceiling = reduces ? min(32, threadsPerThreadgroup) : threadsPerThreadgroup
        var lanes = 1
        while lanes * 2 <= min(innermost, ceiling), threadsPerThreadgroup % (lanes * 2) == 0 {
            lanes *= 2
        }
        return lanes
    }

    /// True when a row's lanes are a contiguous group inside one simdgroup, so a
    /// reduction along that row folds with shuffles alone.
    private var foldsWithinARow: Bool {
        distributesRows && laneWidth <= 32 && 32 % laneWidth == 0
            && laneWidth < threadsPerThreadgroup
    }

    /// Simdgroups per threadgroup — a compile-time constant, which is what lets a
    /// `tt.dot` hand each simdgroup a named set of accumulator registers rather
    /// than a loop-indexed array. Kernels containing a `tt.dot` must be launched
    /// at the reported `threads_per_threadgroup`, which is where this comes from.
    private var simdgroupCount: Int { max(1, threadsPerThreadgroup / 32) }

    // MARK: - Scopes

    private mutating func closeTopFrame() {
        let frame = frames.removeLast()
        frames[frames.count - 1].discardable =
            frames[frames.count - 1].discardable && frame.discardable
        frames[frames.count - 1].statements.append(
            .group(open: frame.open, body: frame.statements, close: frame.close))
    }

    /// The nest currently open.
    private var currentPath: [Int] { frames[frames.count - 1].path }

    private static func isPrefix(_ a: [Int], of b: [Int]) -> Bool {
        a.count <= b.count && Array(b[0..<a.count]) == a
    }

    /// Opens or closes block-axis loops until statements land in the nest `target`.
    ///
    /// Nests form a tree rather than a chain: `p` lives under (M, N) and `acc`
    /// under (M, HEAD_DIM), and moving between them closes the inner loop and
    /// opens the other while the shared M loop stays put — which is what keeps a
    /// value defined in the M loop (an online softmax's running maximum) in scope
    /// across both.
    private mutating func ensureLevel(_ target: [Int], _ loc: SourceLoc) throws {
        while !FunctionEmitter.isPrefix(currentPath, of: target) {
            guard frames[frames.count - 1].kind == .laneLoop else {
                throw CoreError.lowering(
                    "a cross-lane operation (tt.reduce) inside an scf region is not lowered yet: "
                        + "it would have to split the region's lane loop", loc)
            }
            closedLevels.insert(currentPath)
            // A loop that only holds pure definitions is already fully described by
            // `history`, so dropping it here costs nothing: any later use reopens
            // the nest and replays them. Without this, a kernel that hoists a
            // loop to a threadgroup-uniform level emits an empty-looking block
            // loop for every index value it computes before that point and
            // rebuilds afterwards.
            if hoistsUniformRegions, frames[frames.count - 1].discardable {
                frames.removeLast()
            } else {
                closeTopFrame()
            }
        }
        while currentPath.count < target.count {
            let path = Array(target[0...currentPath.count])
            let axis = path[path.count - 1]
            let extent = layout.shape[axis]
            let variable = "tm_i\(axis)"
            let lanes = laneWidth
            let open: String
            if !layout.isUniform(axis), lanes < threadsPerThreadgroup {
                open =
                    "for (uint \(variable) = tm_thread_id.x % \(lanes)u; "
                    + "\(variable) < \(extent)u; \(variable) += \(lanes)u) {"
            } else if !layout.isUniform(axis) {
                open =
                    "for (uint \(variable) = tm_thread_id.x; \(variable) < \(extent)u; "
                    + "\(variable) += tm_threadgroup_size.x) {"
            } else if distributesRows, layout.isUniform(axis), lanes < threadsPerThreadgroup {
                let rows = threadsPerThreadgroup / lanes
                open =
                    "for (uint \(variable) = tm_thread_id.x / \(lanes)u; "
                    + "\(variable) < \(extent)u; \(variable) += \(rows)u) {"
            } else {
                open = "for (uint \(variable) = 0u; \(variable) < \(extent)u; ++\(variable)) {"
            }
            frames.append(Frame(path: path, kind: .laneLoop, open: open))

            if closedLevels.contains(path) {
                if let reason = notRecomputable[path] {
                    throw CoreError.lowering(
                        "cannot reopen block dimension \(axis) to continue after a cross-lane "
                            + "operation: \(reason)", loc)
                }
                for entry in history where entry.path == path {
                    frames[frames.count - 1].statements.append(entry.statement)
                }
            }
        }
    }

    /// Appends a statement at `level`.
    ///
    /// Three things happen here. Inside an `scf` region every statement stays put.
    /// Outside one, a *shallower* statement is hoisted into its own frame instead
    /// of closing the loops around it — Triton emits program-uniform values in
    /// SSA order, interleaved with tensor values, and closing a loop for each one
    /// would litter the output with empty loops. Finally, recomputable statements
    /// are remembered, so a loop reopened after a `tt.reduce` can rebuild them.
    /// `poisons` is what stops the nest being reopened later. It is the default
    /// because a non-recomputable statement usually *defines* something a
    /// reopened nest would have to rebuild (a `tt.reduce`'s fold). A write into a
    /// threadgroup tile defines nothing — the tile holds the value and a reopened
    /// nest simply reads it — so those pass `poisons: false`.
    private mutating func append(
        _ statement: Stmt, level: [Int], recomputable: Bool, sideEffecting: Bool = false,
        poisons: Bool = true, reason: String = "", _ loc: SourceLoc
    ) throws {
        func remember() {
            if recomputable {
                history.append((path: level, statement: statement))
            } else {
                frames[frames.count - 1].discardable = false
                if poisons {
                    notRecomputable[level] = reason.isEmpty ? "it has already been emitted" : reason
                }
            }
            if sideEffecting { frames[frames.count - 1].discardable = false }
        }

        // Rebuilding a tt.dot operand: the loop nest is already open around us and
        // `stage` has picked which of its frames this statement belongs in.
        if stagingDepth > 0 {
            frames[stagingTargetFrame ?? (frames.count - 1)].statements.append(statement)
            return
        }
        if frames.contains(where: { $0.kind == .region }) {
            frames[frames.count - 1].statements.append(statement)
            frames[frames.count - 1].discardable = false
            notRecomputable[frames[frames.count - 1].path] =
                "values defined inside an scf region cannot be recomputed"
            return
        }
        if recomputable, canHoist, level.count < currentPath.count,
            FunctionEmitter.isPrefix(level, of: currentPath),
            let index = frames.lastIndex(where: { $0.path == level })
        {
            frames[index].statements.append(statement)
            remember()
            return
        }
        try ensureLevel(level, loc)
        frames[frames.count - 1].statements.append(statement)
        if sideEffecting { canHoist = false }
        remember()
    }

    // MARK: - Symbol table

    private mutating func register(_ ssa: String, type: TMType) -> String {
        let sanitized = String(ssa.map { $0.isLetter || $0.isNumber ? $0 : "_" })
        let name = "v" + sanitized
        names[ssa] = name
        types[ssa] = type
        return name
    }

    private func name(of ssa: String, _ loc: SourceLoc) throws -> String {
        guard let name = names[ssa] else {
            if isDeferred(ssa) {
                throw CoreError.lowering(
                    "'%\(ssa)' spans the contraction dimension of a tt.dot, so it only exists "
                        + "inside that dot's staging loops; it cannot be used here", loc)
            }
            throw CoreError.lowering("use of undefined value '%\(ssa)'", loc)
        }
        return name
    }

    private func type(of ssa: String, _ loc: SourceLoc) throws -> TMType {
        guard let type = types[ssa] else {
            throw CoreError.lowering("use of undefined value '%\(ssa)'", loc)
        }
        return type
    }

    private func level(of ssa: String) -> [Int] { levels[ssa] ?? [] }

    /// The nest a value of this type belongs in: the axes it varies along, plus
    /// whatever its consumers nest outside them (`BlockLayout.paths`).
    private func shapeLevel(_ ssa: String, _ type: TMType) -> [Int] {
        guard type.shape != nil else { return [] }
        return layout.path(of: ssa)
    }

    /// The nest deep enough for the value and every operand it reads. The axis
    /// sets nest (`BlockLayout` makes each a prefix of its consumers'), so the
    /// union is the deepest of them.
    private func placement(_ ssa: String, _ type: TMType, operands: [String]) -> [Int] {
        var axes = Set(shapeLevel(ssa, type))
        for operand in operands { axes.formUnion(level(of: operand)) }
        return axes.sorted()
    }

    /// Emits `<decl> = <expr>;` at the depth the value needs.
    @discardableResult
    private mutating func define(
        _ ssa: String, type: TMType, expression: String, operands: [String], loc: SourceLoc,
        level forced: [Int]? = nil
    ) throws -> String {
        if stagingDepth == 0, let shape = type.shape, layout.spansContraction(ssa, shape: shape) {
            throw CoreError.lowering(
                "'%\(ssa)' spans block dimension \(layout.axes[ssa]?.last ?? 0), the contraction "
                    + "dimension of a tt.dot; values on that axis have no place in the "
                    + "elementwise iteration space and can only feed a tt.dot operand", loc)
        }
        let level = forced ?? placement(ssa, type, operands: operands)
        let name = register(ssa, type: type)
        levels[ssa] = level
        try append(
            .line("\(try declaration(type, name, loc)) = \(expression);"), level: level,
            recomputable: true, loc)
        // Only the value's real definition updates the shadow: a `tt.dot`'s
        // staging loops rebuild the same subgraph and must not write it again.
        if stagingDepth == 0, let shadow = shadowWrites[ssa] {
            try spillWrite(name, into: shadow, at: level, loc)
        }
        return name
    }

    /// Writes a per-lane value into a threadgroup tile at the lane's block index.
    ///
    /// The nest this happens in decides who writes. When the tile's innermost
    /// axis is the distributed one every element has exactly one owner, so the
    /// write needs no guard; when the nest is threadgroup-uniform every thread
    /// computes the same value for the same slot and writing it redundantly is
    /// how the rest of this emitter already behaves at that depth.
    private mutating func spillWrite(
        _ value: String, into tile: Tile, at level: [Int], _ loc: SourceLoc
    ) throws {
        hasSpilledTiles = true
        try append(
            .line("\(tile.expression) = \(value);"), level: level, recomputable: false,
            sideEffecting: true, poisons: false, loc)
    }

    /// `tt.splat`-like ops that only relabel a value's shape share its variable.
    private mutating func alias(_ ssa: String, to source: String, type: TMType, _ loc: SourceLoc)
        throws
    {
        names[ssa] = try name(of: source, loc)
        types[ssa] = type
        levels[ssa] = level(of: source)
    }

    // MARK: - Type mapping

    private func scalarTypeName(_ type: TMType, _ loc: SourceLoc) throws -> String {
        switch type {
        case .integer(let width):
            switch width {
            case 1: return "bool"
            case 8: return "char"
            case 16: return "short"
            case 32: return "int"
            case 64: return "long"
            default: throw CoreError.unsupportedType("i\(width)", loc)
            }
        case .float(let width):
            return width == 16 ? "half" : "float"
        case .pointer(let pointee):
            return "device \(try scalarTypeName(pointee, loc)) *"
        case .tensor:
            throw CoreError.unsupportedType("nested tensor type \(type)", loc)
        }
    }

    private func declaration(_ type: TMType, _ name: String, _ loc: SourceLoc) throws -> String {
        let element = type.scalarized
        if case .pointer(let pointee) = element {
            if case .pointer = pointee {
                throw CoreError.unsupportedType("pointer-to-pointer \(element)", loc)
            }
            return "device \(try scalarTypeName(pointee, loc)) *\(name)"
        }
        return "\(try scalarTypeName(element, loc)) \(name)"
    }

    private func unsignedName(_ type: TMType, _ loc: SourceLoc) throws -> String {
        switch type.scalarized {
        case .integer(let width):
            switch width {
            case 1: return "bool"
            case 8: return "uchar"
            case 16: return "ushort"
            case 32: return "uint"
            case 64: return "ulong"
            default: throw CoreError.unsupportedType("i\(width)", loc)
            }
        default:
            throw CoreError.unsupportedType("\(type) in an unsigned operation", loc)
        }
    }

    // MARK: - Instruction lowering

    /// Single-result ops only; `scf` regions bind several names at once and are
    /// never deferred as a unit.
    private static func soleResult(_ kind: OpKind) -> String? {
        switch kind {
        case .forLoop, .ifOp: return nil
        default:
            let results = kind.resultNames
            return results.count == 1 ? results[0] : nil
        }
    }

    private mutating func emit(_ instruction: Instruction) throws {
        let loc = instruction.loc
        for result in instruction.kind.resultNames where valueOrder[result] == nil {
            definitions[result] = instruction
            valueOrder[result] = nextValueOrder
            nextValueOrder += 1
        }
        // Values that only feed a tt.dot are rebuilt inside that dot's staging
        // loops, over an index space that includes the contraction dimension.
        if let result = FunctionEmitter.soleResult(instruction.kind), isDeferred(result) {
            return
        }

        switch instruction.kind {
        case .ret:
            return

        case .constant(let result, let type, let value):
            try define(
                result, type: type, expression: literal(value, type, loc), operands: [], loc: loc)

        case .programID(let result, let axis):
            usesProgramID = true
            try define(
                result, type: .integer(width: 32),
                expression: "int(tm_program_id.\(FunctionEmitter.axisNames[axis]))", operands: [],
                loc: loc)

        case .numPrograms(let result, let axis):
            usesGridSize = true
            try define(
                result, type: .integer(width: 32),
                expression: "int(tm_grid_size.\(FunctionEmitter.axisNames[axis]))", operands: [],
                loc: loc)

        case .makeRange(let result, let type, let start, let end):
            guard case .tensor(let shape, let element) = type, element == .integer(width: 32),
                shape.count == 1
            else {
                throw CoreError.lowering(
                    "tt.make_range must produce a 1-D tensor<Nxi32>, found \(type)", loc)
            }
            guard end - start == shape[0] else {
                throw CoreError.lowering(
                    "tt.make_range [\(start), \(end)) does not match its result length \(shape[0])",
                    loc)
            }
            let expression: String
            if shape[0] == 1 {
                expression = "\(start)"
            } else {
                let axis = layout.axes[result]?.first ?? 0
                expression = start == 0 ? "int(tm_i\(axis))" : "int(tm_i\(axis)) + \(start)"
            }
            try define(result, type: type, expression: expression, operands: [], loc: loc)

        case .splat(let result, let resultType, let source):
            let sourceType = try type(of: source, loc)
            guard !sourceType.isTensor else {
                throw CoreError.lowering("tt.splat operand must be a scalar, found \(sourceType)", loc)
            }
            guard resultType.scalarized == sourceType else {
                throw CoreError.lowering(
                    "tt.splat result \(resultType) does not match operand type \(sourceType)", loc)
            }
            try define(
                result, type: resultType, expression: try name(of: source, loc), operands: [source],
                loc: loc)

        case .expandDims(let result, let resultType, let source, let axis):
            let sourceType = try type(of: source, loc)
            guard let sourceShape = sourceType.shape, let resultShape = resultType.shape,
                resultShape.count == sourceShape.count + 1, axis <= sourceShape.count,
                resultShape[axis] == 1,
                Array(resultShape[0..<axis] + resultShape[(axis + 1)...]) == sourceShape
            else {
                throw CoreError.lowering(
                    "tt.expand_dims axis \(axis) cannot turn \(sourceType) into \(resultType)", loc)
            }
            // Pure relabelling: the value per lane is unchanged.
            try alias(result, to: source, type: resultType, loc)

        case .trans(let result, let resultType, let source, let order):
            let sourceType = try type(of: source, loc)
            guard let sourceShape = sourceType.shape, let resultShape = resultType.shape,
                order.count == sourceShape.count, resultShape.count == sourceShape.count,
                resultShape == order.map({ sourceShape[$0] })
            else {
                throw CoreError.lowering(
                    "tt.trans with order \(order) cannot turn \(sourceType) into \(resultType)", loc)
            }
            // A transpose is a relabelling of which block axis each dimension
            // indexes, and `Layout.swift` has already done it: the two values are
            // the same per-lane scalar at the same block *point*, so no code is
            // emitted at all. What it costs is a nesting constraint — the source
            // says one axis is outside the other and the result says the reverse
            // — which only a value that never enters an elementwise nest can
            // avoid. A `tt.dot` operand is exactly that (it is rebuilt inside the
            // dot's own staging loops, which walk the tile's axes in whichever
            // order the tile wants); anything materialised is refused by
            // `LayoutInference`, by name, before this runs.
            try alias(result, to: source, type: resultType, loc)

        case .broadcast(let result, let resultType, let source):
            let sourceType = try type(of: source, loc)
            guard let sourceShape = sourceType.shape, let resultShape = resultType.shape,
                sourceShape.count == resultShape.count,
                zip(sourceShape, resultShape).allSatisfy({ $0 == $1 || $0 == 1 })
            else {
                throw CoreError.lowering(
                    "tt.broadcast cannot turn \(sourceType) into \(resultType)", loc)
            }
            try alias(result, to: source, type: resultType, loc)

        case .addPtr(let result, let pointer, let offset):
            let pointerType = try type(of: pointer, loc)
            let offsetType = try type(of: offset, loc)
            guard case .pointer = pointerType.scalarized else {
                throw CoreError.lowering("tt.addptr expects a pointer, found \(pointerType)", loc)
            }
            guard offsetType.isIntegerLike else {
                throw CoreError.lowering(
                    "tt.addptr offset must be an integer, found \(offsetType)", loc)
            }
            let resultType =
                offsetType.isTensor ? offsetType.withElement(pointerType.scalarized) : pointerType
            try define(
                result, type: resultType,
                expression: "\(try name(of: pointer, loc)) + \(try name(of: offset, loc))",
                operands: [pointer, offset], loc: loc)

        case .intBinary(let result, let op, let lhs, let rhs):
            let type = try binaryOperandType(lhs, rhs, "arith", loc)
            guard type.isIntegerLike else {
                throw CoreError.lowering("integer arithmetic on \(type)", loc)
            }
            let l = try name(of: lhs, loc)
            let r = try name(of: rhs, loc)
            let unsigned = try unsignedName(type, loc)
            let isBool = type.scalarized == .integer(width: 1)
            let expression: String
            switch op {
            case .add: expression = "\(l) + \(r)"
            case .sub: expression = "\(l) - \(r)"
            case .mul: expression = "\(l) * \(r)"
            case .divs: expression = "\(l) / \(r)"
            case .rems: expression = "\(l) % \(r)"
            case .divu: expression = "\(unsigned)(\(l)) / \(unsigned)(\(r))"
            case .remu: expression = "\(unsigned)(\(l)) % \(unsigned)(\(r))"
            case .and: expression = isBool ? "\(l) && \(r)" : "\(l) & \(r)"
            case .or: expression = isBool ? "\(l) || \(r)" : "\(l) | \(r)"
            case .xor: expression = isBool ? "\(l) != \(r)" : "\(l) ^ \(r)"
            case .shl: expression = "\(l) << \(r)"
            case .shrs: expression = "\(l) >> \(r)"
            case .shru: expression = "\(unsigned)(\(l)) >> \(unsigned)(\(r))"
            case .maxs: expression = "max(\(l), \(r))"
            case .mins: expression = "min(\(l), \(r))"
            case .maxu: expression = "\(try scalarTypeName(type.scalarized, loc))(max(\(unsigned)(\(l)), \(unsigned)(\(r))))"
            case .minu: expression = "\(try scalarTypeName(type.scalarized, loc))(min(\(unsigned)(\(l)), \(unsigned)(\(r))))"
            }
            try define(result, type: type, expression: expression, operands: [lhs, rhs], loc: loc)

        case .floatBinary(let result, let op, let lhs, let rhs):
            let type = try binaryOperandType(lhs, rhs, "arith", loc)
            guard type.isFloatLike else {
                throw CoreError.lowering("floating-point arithmetic on \(type)", loc)
            }
            let l = try name(of: lhs, loc)
            let r = try name(of: rhs, loc)
            let expression: String
            switch op {
            case .add: expression = "\(l) + \(r)"
            case .sub: expression = "\(l) - \(r)"
            case .mul: expression = "\(l) * \(r)"
            case .div: expression = "\(l) / \(r)"
            case .maximum: expression = "max(\(l), \(r))"
            case .minimum: expression = "min(\(l), \(r))"
            }
            try define(result, type: type, expression: expression, operands: [lhs, rhs], loc: loc)

        case .intCompare(let result, let predicate, let lhs, let rhs):
            let type = try binaryOperandType(lhs, rhs, "arith.cmpi", loc)
            guard type.isIntegerLike else {
                throw CoreError.lowering("arith.cmpi on \(type)", loc)
            }
            let l = try name(of: lhs, loc)
            let r = try name(of: rhs, loc)
            let expression: String
            switch predicate {
            case "eq": expression = "\(l) == \(r)"
            case "ne": expression = "\(l) != \(r)"
            case "slt": expression = "\(l) < \(r)"
            case "sle": expression = "\(l) <= \(r)"
            case "sgt": expression = "\(l) > \(r)"
            case "sge": expression = "\(l) >= \(r)"
            case "ult", "ule", "ugt", "uge":
                let cast = try unsignedName(type, loc)
                let symbol = ["ult": "<", "ule": "<=", "ugt": ">", "uge": ">="][predicate]!
                expression = "\(cast)(\(l)) \(symbol) \(cast)(\(r))"
            default:
                throw CoreError.unsupportedOp("arith.cmpi \(predicate)", loc)
            }
            try define(
                result, type: type.withElement(.integer(width: 1)), expression: expression,
                operands: [lhs, rhs], loc: loc)

        case .floatCompare(let result, let predicate, let lhs, let rhs):
            let type = try binaryOperandType(lhs, rhs, "arith.cmpf", loc)
            guard type.isFloatLike else {
                throw CoreError.lowering("arith.cmpf on \(type)", loc)
            }
            let l = try name(of: lhs, loc)
            let r = try name(of: rhs, loc)
            guard let symbol = FunctionEmitter.floatPredicates[predicate] else {
                throw CoreError.unsupportedOp("arith.cmpf \(predicate)", loc)
            }
            try define(
                result, type: type.withElement(.integer(width: 1)),
                expression: "\(l) \(symbol) \(r)", operands: [lhs, rhs], loc: loc)

        case .cast(let result, let op, let source, let resultType):
            try emitCast(result: result, op: op, source: source, resultType: resultType, loc: loc)

        case .unary(let result, let op, let source):
            let sourceType = try type(of: source, loc)
            let function = try FunctionEmitter.mathFunction(op, sourceType, loc)
            try define(
                result, type: sourceType,
                expression: "\(function)(\(try name(of: source, loc)))", operands: [source], loc: loc)

        case .select(let result, let condition, let whenTrue, let whenFalse):
            let valueType = try binaryOperandType(whenTrue, whenFalse, "arith.select", loc)
            let conditionType = try type(of: condition, loc)
            guard conditionType.scalarized == .integer(width: 1) else {
                throw CoreError.lowering(
                    "arith.select condition must be i1, found \(conditionType)", loc)
            }
            guard !conditionType.isTensor || conditionType.shape == valueType.shape else {
                throw CoreError.lowering(
                    "arith.select condition shape \(conditionType) does not match \(valueType)",
                    loc)
            }
            try define(
                result, type: valueType,
                expression: "\(try name(of: condition, loc)) ? \(try name(of: whenTrue, loc)) "
                    + ": \(try name(of: whenFalse, loc))",
                operands: [condition, whenTrue, whenFalse], loc: loc)

        case .reduce(let result, let source, let axis, let op):
            try emitReduce(result: result, source: source, axis: axis, op: op, loc: loc)

        case .dot(let dot):
            try emitDot(dot, loc: loc)

        case .load(let result, let pointer, let mask, let other):
            let pointerType = try type(of: pointer, loc)
            guard case .pointer(let pointee) = pointerType.scalarized else {
                throw CoreError.lowering("tt.load expects a pointer, found \(pointerType)", loc)
            }
            let resultType = pointerType.withElement(pointee)
            var operands = [pointer]
            var expression = "*\(try name(of: pointer, loc))"
            if let mask {
                try checkShape(mask, against: pointerType, "tt.load mask", loc)
                operands.append(mask)
                let fallback: String
                if let other {
                    let otherType = try type(of: other, loc)
                    guard otherType.scalarized == pointee else {
                        throw CoreError.lowering(
                            "tt.load 'other' operand is \(otherType), expected \(pointee)", loc)
                    }
                    operands.append(other)
                    fallback = try name(of: other, loc)
                } else {
                    fallback = literal(pointee.isFloatLike ? .float(0) : .integer(0), pointee, loc)
                }
                expression = "\(try name(of: mask, loc)) ? \(expression) : \(fallback)"
            } else if other != nil {
                throw CoreError.lowering("tt.load with 'other' but no mask", loc)
            }
            try define(result, type: resultType, expression: expression, operands: operands, loc: loc)

        case .store(let pointer, let value, let mask):
            let pointerType = try type(of: pointer, loc)
            let valueType = try type(of: value, loc)
            guard case .pointer(let pointee) = pointerType.scalarized else {
                throw CoreError.lowering("tt.store expects a pointer, found \(pointerType)", loc)
            }
            guard valueType.scalarized == pointee else {
                throw CoreError.lowering(
                    "tt.store value type \(valueType) does not match pointee \(pointee)", loc)
            }
            guard valueType.shape == pointerType.shape else {
                throw CoreError.lowering(
                    "tt.store value shape \(valueType) does not match pointer shape \(pointerType)",
                    loc)
            }
            var operands = [pointer, value]
            var line = "*\(try name(of: pointer, loc)) = \(try name(of: value, loc));"
            var conditions: [String] = []
            if let mask {
                try checkShape(mask, against: pointerType, "tt.store mask", loc)
                operands.append(mask)
                conditions.append(try name(of: mask, loc))
            }
            var axes: Set<Int> = []
            for operand in operands { axes.formUnion(level(of: operand)) }
            let level = axes.sorted()
            // Only a nest's innermost loop is distributed over threads; a store
            // whose own nest ends on a uniform axis runs identically in every
            // thread, so one thread does the writing.
            if rank > 0, level.last.map({ layout.isUniform($0) }) ?? true {
                conditions.insert(
                    distributesRows && laneWidth < threadsPerThreadgroup
                        ? "tm_thread_id.x % \(laneWidth)u == 0u" : "tm_thread_id.x == 0u",
                    at: 0)
            }
            if !conditions.isEmpty {
                line = "if (\(conditions.joined(separator: " && "))) { \(line) }"
            }
            try append(
                .line(line), level: level, recomputable: false, sideEffecting: true,
                reason: "a tt.store cannot be recomputed", loc)

        case .atomicRMW(let atomic):
            try emitAtomicRMW(atomic, loc: loc)

        case .atomicCAS(let atomic):
            try emitAtomicCAS(atomic, loc: loc)

        case .forLoop(let loop):
            try emitFor(loop, loc: loc)

        case .ifOp(let branch):
            try emitIf(branch, loc: loc)

        case .yield(let values):
            guard let targets = yieldTargets.last else {
                throw CoreError.lowering("\(instruction.mnemonic) outside a region", loc)
            }
            guard targets.count == values.count else {
                throw CoreError.lowering(
                    "\(instruction.mnemonic) yields \(values.count) values for \(targets.count) "
                        + "region results", loc)
            }
            for (target, value) in zip(targets, values) {
                switch target {
                case .deferred:
                    continue
                case .tile(let tile):
                    guard tiles[value]?.name == tile else {
                        throw CoreError.lowering(
                            "'%\(value)' is yielded into a tt.dot accumulator but is not the "
                                + "result of the tt.dot that updates it; the accumulator lives in "
                                + "threadgroup memory and is updated in place", loc)
                    }
                case .spilled(let tile, let shadow, let expected):
                    guard value == expected else {
                        throw CoreError.lowering(
                            "scf.yield returns '%\(value)' where '%\(expected)' was expected for "
                                + "the spilled carried tensor in '\(tile.name)'", loc)
                    }
                    // The new value is already in the shadow — written where it was
                    // defined, or, when it is itself a tile (another dot's result),
                    // copied straight from there.
                    spillCopies.append((from: tiles[value] ?? shadow, to: tile))
                case .variable(let variable):
                    frames[frames.count - 1].statements.append(
                        .line("\(variable) = \(try name(of: value, loc));"))
                    frames[frames.count - 1].discardable = false
                }
            }
        }
    }

