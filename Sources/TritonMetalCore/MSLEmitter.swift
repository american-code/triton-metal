    // MARK: - Casts and math

    private mutating func emitCast(
        result: String, op: CastOp, source: String, resultType: TMType, loc: SourceLoc
    ) throws {
        let sourceType = try type(of: source, loc)
        guard sourceType.shape == resultType.shape else {
            throw CoreError.lowering(
                "arith.\(op.rawValue) changes shape: \(sourceType) to \(resultType)", loc)
        }
        let from = sourceType.scalarized
        let to = resultType.scalarized
        let value = try name(of: source, loc)
        let target = try scalarTypeName(to, loc)

        func requireIntToFloat() throws {
            guard from.isIntegerLike, to.isFloatLike else {
                throw CoreError.lowering(
                    "arith.\(op.rawValue) expects an integer source and a float result, "
                        + "found \(sourceType) to \(resultType)", loc)
            }
        }
        func requireFloatToInt() throws {
            guard from.isFloatLike, to.isIntegerLike else {
                throw CoreError.lowering(
                    "arith.\(op.rawValue) expects a float source and an integer result, "
                        + "found \(sourceType) to \(resultType)", loc)
            }
        }
        func requireIntWidths(widen: Bool) throws {
            guard case .integer(let a) = from, case .integer(let b) = to else {
                throw CoreError.lowering(
                    "arith.\(op.rawValue) expects integer operands, found \(sourceType) to "
                        + "\(resultType)", loc)
            }
            guard widen ? b > a : b < a else {
                throw CoreError.lowering(
                    "arith.\(op.rawValue) must \(widen ? "widen" : "narrow"), found i\(a) to i\(b)",
                    loc)
            }
        }
        func requireFloatWidths(widen: Bool) throws {
            guard case .float(let a) = from, case .float(let b) = to else {
                throw CoreError.lowering(
                    "arith.\(op.rawValue) expects float operands, found \(sourceType) to "
                        + "\(resultType)", loc)
            }
            guard widen ? b > a : b < a else {
                throw CoreError.lowering(
                    "arith.\(op.rawValue) must \(widen ? "widen" : "narrow"), found f\(a) to f\(b)",
                    loc)
            }
        }

        var expression: String
        switch op {
        case .sitofp:
            try requireIntToFloat()
            expression = "\(target)(\(value))"
        case .uitofp:
            try requireIntToFloat()
            expression = "\(target)(\(try unsignedName(from, loc))(\(value)))"
        case .fptosi:
            try requireFloatToInt()
            expression = "\(target)(\(value))"
        case .fptoui:
            try requireFloatToInt()
            expression = "\(target)(\(try unsignedName(to, loc))(\(value)))"
        case .extsi:
            try requireIntWidths(widen: true)
            expression = "\(target)(\(value))"
        case .extui:
            try requireIntWidths(widen: true)
            expression = "\(target)(\(try unsignedName(from, loc))(\(value)))"
        case .trunci:
            try requireIntWidths(widen: false)
            expression = to == .integer(width: 1) ? "((\(value) & 1) != 0)" : "\(target)(\(value))"
        case .truncf:
            try requireFloatWidths(widen: false)
            expression = "\(target)(\(value))"
        case .extf:
            try requireFloatWidths(widen: true)
            expression = "\(target)(\(value))"
        case .bitcast:
            guard from.scalarByteWidth == to.scalarByteWidth else {
                throw CoreError.lowering(
                    "arith.bitcast between different widths: \(sourceType) to \(resultType)", loc)
            }
            expression = "as_type<\(target)>(\(value))"
        }
        try define(
            result, type: resultType, expression: expression, operands: [source], loc: loc)
    }

    /// Metal's `precise::` namespace where it exists, the default namespace
    /// otherwise. Correctness over speed: `fast::` is never used, and the runtime
    /// compiles with fast-math disabled (see `MetalRuntime.makeLibrary`).
    static func mathFunction(_ op: MathOp, _ type: TMType, _ loc: SourceLoc) throws -> String {
        switch op {
        case .absi:
            guard type.isIntegerLike else {
                throw CoreError.lowering("math.absi on \(type)", loc)
            }
            return "abs"
        default:
            guard type.isFloatLike else {
                throw CoreError.lowering("math.\(op.rawValue) on \(type)", loc)
            }
        }
        switch op {
        case .exp: return "precise::exp"
        case .exp2: return "precise::exp2"
        case .log: return "precise::log"
        case .log2: return "precise::log2"
        case .sqrt: return "precise::sqrt"
        case .rsqrt: return "precise::rsqrt"
        case .sin: return "precise::sin"
        case .cos: return "precise::cos"
        // No precise::/fast:: variants exist for these; the default namespace is
        // already the accurate implementation.
        case .tanh: return "tanh"
        case .erf: return "tm_erf"
        case .floor: return "floor"
        case .ceil: return "ceil"
        case .absf: return "fabs"
        case .absi: return "abs"
        }
    }

    // MARK: - Atomics

    /// `tt.atomic_rmw` — one device read-modify-write per block point, returning
    /// the old value.
    ///
    /// Metal's atomics are 32-bit and live in the `device` (or `threadgroup`)
    /// address space; a Triton `!tt.ptr<f32>` is already a `device float *`, so
    /// the lowering is a cast of the address and a call. What it is *not* is
    /// ordered: MSL declares exactly one memory order for these
    /// (`memory_order_relaxed` — `memory_order_acq_rel` is not a declared
    /// identifier at all), so Triton's `sem` and `scope` are parsed and dropped.
    /// The operation itself is atomic; nothing else about it is ordered.
    private mutating func emitAtomicRMW(_ atomic: AtomicRMW, loc: SourceLoc) throws {
        let pointerType = try type(of: atomic.pointer, loc)
        guard case .pointer(let pointee) = pointerType.scalarized else {
            throw CoreError.lowering(
                "tt.atomic_rmw expects a pointer, found \(pointerType)", loc)
        }
        let valueType = try type(of: atomic.value, loc)
        guard valueType.scalarized == pointee else {
            throw CoreError.lowering(
                "tt.atomic_rmw value type \(valueType) does not match pointee \(pointee)", loc)
        }
        guard valueType.shape == pointerType.shape else {
            throw CoreError.lowering(
                "tt.atomic_rmw value shape \(valueType) does not match pointer shape "
                    + "\(pointerType)", loc)
        }
        let expression = try atomicRMWExpression(
            op: atomic.op, pointee: pointee,
            pointer: try name(of: atomic.pointer, loc), value: try name(of: atomic.value, loc),
            loc: loc)

        var operands = [atomic.pointer, atomic.value]
        var conditions: [String] = []
        if let mask = atomic.mask {
            try checkShape(mask, against: pointerType, "tt.atomic_rmw mask", loc)
            operands.append(mask)
            conditions.append(try name(of: mask, loc))
        }
        try emitAtomic(
            result: atomic.result, resultType: pointerType.withElement(pointee), pointee: pointee,
            expression: expression, operands: operands, conditions: conditions, what: "tt.atomic_rmw",
            loc: loc)
    }

    /// `tt.atomic_cas` — unmasked in Triton's own op definition, so this is the
    /// same shape without the guard.
    private mutating func emitAtomicCAS(_ atomic: AtomicCAS, loc: SourceLoc) throws {
        let pointerType = try type(of: atomic.pointer, loc)
        guard case .pointer(let pointee) = pointerType.scalarized else {
            throw CoreError.lowering("tt.atomic_cas expects a pointer, found \(pointerType)", loc)
        }
        for (operand, role) in [(atomic.compare, "compare"), (atomic.value, "value")] {
            let type = try type(of: operand, loc)
            guard type.scalarized == pointee else {
                throw CoreError.lowering(
                    "tt.atomic_cas \(role) type \(type) does not match pointee \(pointee)", loc)
            }
            guard type.shape == pointerType.shape else {
                throw CoreError.lowering(
                    "tt.atomic_cas \(role) shape \(type) does not match pointer shape "
                        + "\(pointerType)", loc)
            }
        }
        switch pointee {
        case .integer(32), .float(32):
            usesAtomicCAS = true
        default:
            throw CoreError.unsupportedOp(
                "tt.atomic_cas on \(pointee) (Metal's atomics cover 32-bit int and float only)",
                loc)
        }
        let expression =
            "tm_atomic_cas(\(try name(of: atomic.pointer, loc)), "
            + "\(try name(of: atomic.compare, loc)), \(try name(of: atomic.value, loc)))"
        try emitAtomic(
            result: atomic.result, resultType: pointerType.withElement(pointee), pointee: pointee,
            expression: expression, operands: [atomic.pointer, atomic.compare, atomic.value],
            conditions: [], what: "tt.atomic_cas", loc: loc)
    }

    /// The half both atomics share: placement, the single-writer guard a
    /// threadgroup-uniform nest needs, and the non-recomputable statement.
    ///
    /// The guard is a correctness requirement rather than the optimisation it is
    /// for `tt.store`. Only a nest's innermost loop is distributed over threads,
    /// so a statement whose nest ends on a uniform axis runs in *every* thread —
    /// which for a store writes the same bytes twice and for an atomic add would
    /// add the same contribution `threadsPerThreadgroup` times.
    private mutating func emitAtomic(
        result: String, resultType: TMType, pointee: TMType, expression: String,
        operands: [String], conditions: [String], what: String, loc: SourceLoc
    ) throws {
        var axes = Set(shapeLevel(result, resultType))
        for operand in operands { axes.formUnion(level(of: operand)) }
        let level = axes.sorted()

        var conditions = conditions
        let uniformNest = rank > 0 && (level.last.map { layout.isUniform($0) } ?? true)
        if uniformNest {
            conditions.insert(
                distributesRows && laneWidth < threadsPerThreadgroup
                    ? "tm_thread_id.x % \(laneWidth)u == 0u" : "tm_thread_id.x == 0u",
                at: 0)
            // One thread performs the access, so only that thread can be told what
            // was there before. Refused by name rather than returning zero in the
            // other lanes.
            if readValues.contains(result) {
                throw CoreError.lowering(
                    "'%\(result)' is the old value returned by a \(what) whose loop nest ends on "
                        + "a block dimension every thread walks, so the access is performed by one "
                        + "thread of the threadgroup and the returned value exists only there; "
                        + "the result cannot be used. Index the atomic by the distributed block "
                        + "dimension, or drop the result", loc)
            }
        }

        let name = register(result, type: resultType)
        levels[result] = level
        let declaration = try declaration(resultType, name, loc)
        let line: String
        if conditions.isEmpty {
            line = "\(declaration) = \(expression);"
        } else {
            // A lane whose mask is false performs no access and reads back zero,
            // which is what Triton documents for a masked atomic.
            let zero = literal(pointee.isFloatLike ? .float(0) : .integer(0), pointee, loc)
            line =
                "\(declaration) = \(zero); "
                + "if (\(conditions.joined(separator: " && "))) { \(name) = \(expression); }"
        }
        try append(
            .line(line), level: level, recomputable: false, sideEffecting: true,
            reason: "a \(what) cannot be recomputed", loc)
    }

    /// The MSL call one `tt.atomic_rmw` kind lowers to, for one pointee type.
    ///
    /// Verified empirically on an M1 Pro (Metal 3): `atomic_float` supports
    /// `fetch_add`, `fetch_sub`, `exchange` and `compare_exchange_weak` but **not**
    /// `fetch_max`/`fetch_min`; `atomic_int`/`atomic_uint` support all of them;
    /// there are no 16-bit or 64-bit atomics at all.
    private mutating func atomicRMWExpression(
        op: AtomicRMWOp, pointee: TMType, pointer: String, value: String, loc: SourceLoc
    ) throws -> String {
        func refuse(_ why: String) -> CoreError {
            CoreError.unsupportedOp("tt.atomic_rmw \(op.rawValue) on \(pointee) (\(why))", loc)
        }
        func call(_ verb: String, _ type: String, _ operand: String) -> String {
            "atomic_\(verb)_explicit((device \(type) *)(\(pointer)), \(operand), "
                + "memory_order_relaxed)"
        }

        switch pointee {
        case .float(let width):
            guard width == 32 else {
                throw refuse("Metal has no 16-bit atomics; there is no atomic<half>")
            }
            switch op {
            // Triton spells a float add `fadd`; `add` on a float pointer is not
            // something its frontend emits, but it means the same thing.
            case .fadd, .add: return call("fetch_add", "atomic_float", value)
            case .exch: return call("exchange", "atomic_float", value)
            case .max:
                usesFloatAtomicMinMax = true
                return "tm_atomic_fmax(\(pointer), \(value))"
            case .min:
                usesFloatAtomicMinMax = true
                return "tm_atomic_fmin(\(pointer), \(value))"
            case .and, .or, .xor, .umax, .umin:
                throw refuse("integer-only operation")
            }

        case .integer(let width):
            guard width == 32 else {
                throw refuse(
                    width == 64
                        ? "Metal has no 64-bit atomics" : "Metal's atomics are 32-bit; widen to i32"
                )
            }
            switch op {
            case .add: return call("fetch_add", "atomic_int", value)
            case .and: return call("fetch_and", "atomic_int", value)
            case .or: return call("fetch_or", "atomic_int", value)
            case .xor: return call("fetch_xor", "atomic_int", value)
            case .max: return call("fetch_max", "atomic_int", value)
            case .min: return call("fetch_min", "atomic_int", value)
            case .exch: return call("exchange", "atomic_int", value)
            case .umax: return "int(\(call("fetch_max", "atomic_uint", "uint(\(value))")))"
            case .umin: return "int(\(call("fetch_min", "atomic_uint", "uint(\(value))")))"
            case .fadd: throw refuse("floating-point operation")
            }

        default:
            throw refuse("only f32 and i32 device pointers are lowered")
        }
    }

    // MARK: - Reductions

    private mutating func emitReduce(
        result: String, source: String, axis: Int, op: ReduceOp, loc: SourceLoc
    ) throws {
        let sourceType = try type(of: source, loc)
        guard let shape = sourceType.shape else {
            throw CoreError.lowering("tt.reduce expects a tensor, found \(sourceType)", loc)
        }
        guard axis == shape.count - 1 else {
            throw CoreError.unsupportedOp(
                "tt.reduce over axis \(axis) of a \(shape.count)-D tensor (only the last axis, "
                    + "which is the axis distributed across threads, is lowered)", loc)
        }
        let sourcePath = layout.path(of: source)
        guard let map = layout.axes[source], axis < map.count else {
            throw CoreError.lowering(
                "tt.reduce's operand '%\(source)' has no block layout", loc)
        }
        guard sourcePath.last == map[axis], !layout.isUniform(map[axis]) else {
            throw CoreError.lowering(
                "tt.reduce must reduce the innermost block dimension of its operand's loop nest "
                    + "(the one strided across the threadgroup); '%\(source)' is nested over "
                    + "block dimensions \(sourcePath) and is being reduced along \(map[axis])",
                loc)
        }
        let element = sourceType.scalarized
        guard element.isFloatLike || element.isIntegerLike else {
            throw CoreError.lowering("tt.reduce over \(sourceType)", loc)
        }

        usesSimdgroups = true
        let index = reductionCount
        reductionCount += 1
        let accumulator = "tm_acc\(index)"
        let scratch = "tm_scratch\(index)"
        let elementName = try scalarTypeName(element, loc)
        let combine: (String, String) -> String = { a, b in
            switch op {
            case .add: return "\(a) + \(b)"
            case .max: return "max(\(a), \(b))"
            case .min: return "min(\(a), \(b))"
            }
        }

        // Two folds. A row that owns a *group* of lanes inside one simdgroup
        // folds with shuffles alone; a row that owns the whole threadgroup has to
        // go through threadgroup memory and two barriers, which is the only
        // shape a rank-1 kernel has.
        let lanes = laneWidth
        let withinARow = foldsWithinARow && sourcePath.count >= 2
        if !withinARow {
            requireSimdCount()
            preamble.append(.line("threadgroup \(elementName) \(scratch)[32];"))
            threadgroupBytes += 32 * (element.scalarByteWidth ?? 4)
        }

        // Accumulate inside the innermost loop, one partial per thread.
        try ensureLevel(sourcePath, loc)
        frames[frames.count - 2].statements.append(
            .line("\(elementName) \(accumulator) = \(identity(op, element, loc));"))
        frames[frames.count - 2].discardable = false
        frames[frames.count - 1].statements.append(
            .line("\(accumulator) = \(combine(accumulator, try name(of: source, loc)));"))
        frames[frames.count - 1].discardable = false
        let outer = Array(sourcePath.dropLast())
        try ensureLevel(outer, loc)
        let resultType = sourceType.reducingLastDimension()
        let reason = "a tt.reduce cannot be recomputed"

        if withinARow {
            try append(
                .line(
                    "// tt.reduce (\(op.rawValue)): fold within the \(lanes) lanes of this row"),
                level: outer, recomputable: false, reason: reason, loc)
            try append(
                .line(
                    "for (ushort tm_delta = \(lanes / 2); tm_delta > 0; tm_delta >>= 1) { "
                        + "\(accumulator) = "
                        + "\(combine(accumulator, "simd_shuffle_down(\(accumulator), tm_delta)")); }"),
                level: outer, recomputable: false, reason: reason, loc)
            let origin = lanes == 32
                ? "0" : "(tm_simd_lane / \(lanes)u) * \(lanes)u"
            let reduced = try define(
                result, type: resultType,
                expression: "simd_shuffle(\(accumulator), \(origin))", operands: [], loc: loc,
                level: outer)
            try spillReduction(result, named: reduced, type: resultType, at: outer, loc)
            return
        }

        let lines: [Stmt] = [
            .line(
                "// tt.reduce (\(op.rawValue)): fold within each simdgroup, then across them"),
            .line(
                "for (ushort tm_delta = 16; tm_delta > 0; tm_delta >>= 1) { "
                    + "\(accumulator) = \(combine(accumulator, "simd_shuffle_down(\(accumulator), tm_delta)")); }"),
            .line("threadgroup_barrier(mem_flags::mem_threadgroup);"),
            .line("if (tm_simd_lane == 0) { \(scratch)[tm_simd_group] = \(accumulator); }"),
            .line("threadgroup_barrier(mem_flags::mem_threadgroup);"),
        ]
        for line in lines {
            try append(line, level: outer, recomputable: false, reason: reason, loc)
        }

        let reduced = try define(
            result, type: resultType, expression: "\(scratch)[0]",
            operands: [], loc: loc, level: outer)
        try append(
            .line(
                "for (uint tm_k = 1; tm_k < tm_simd_count; ++tm_k) { "
                    + "\(reduced) = \(combine(reduced, "\(scratch)[tm_k]")); }"),
            level: outer, recomputable: false, reason: reason, loc)

        try spillReduction(result, named: reduced, type: resultType, at: outer, loc)
    }

    /// A reduction is the one thing a `tt.dot`'s staging loops cannot rebuild, so
    /// a result some dot operand depends on is written into a small threadgroup
    /// array where it is computed and read out of it there —
    /// FlashAttention-2's running row maximum, which its
    /// `p = exp2(qk - m_ij)` needs inside the staging nest of the second dot.
    private mutating func spillReduction(
        _ result: String, named variable: String, type: TMType, at level: [Int], _ loc: SourceLoc
    ) throws {
        guard spilledReductions.contains(result), let shape = type.shape, !shape.isEmpty else {
            return
        }
        let tile = try spillTile("reduce", for: result, type: type, loc)
        try spillWrite(variable, into: tile, at: level, loc)
        registerTile(result, tile, type: type)
    }

    /// A threadgroup array shaped like the block axes a per-lane value spans, for
    /// values that have to survive outside the nest that computes them.
    private mutating func spillTile(
        _ prefix: String, for ssa: String, type: TMType, _ loc: SourceLoc
    ) throws -> Tile {
        guard let shape = type.shape, let map = layout.axes[ssa] else {
            throw CoreError.lowering("cannot spill the scalar '%\(ssa)' into threadgroup memory", loc)
        }
        var dimensions: [(axis: Int, extent: Int)] = []
        for (index, size) in shape.enumerated() where size > 1 {
            dimensions.append((axis: map[index], extent: size))
        }
        dimensions.sort { $0.axis < $1.axis }
        hasSpilledTiles = true
        switch dimensions.count {
        case 1:
            var tile = try allocateTile(
                prefix, element: type.scalarized, rows: dimensions[0].extent, columns: 1,
                rowAxis: dimensions[0].axis, columnAxis: dimensions[0].axis,
                rowGranularity: 1, columnGranularity: 1, loc)
            tile.hasColumns = false
            return tile
        case 2:
            return try allocateTile(
                prefix, element: type.scalarized, rows: dimensions[0].extent,
                columns: dimensions[1].extent, rowAxis: dimensions[0].axis,
                columnAxis: dimensions[1].axis, loc)
        default:
            throw CoreError.lowering(
                "'%\(ssa)' spans \(dimensions.count) block dimensions; only rank-1 and rank-2 "
                    + "values can be spilled into threadgroup memory", loc)
        }
    }

    private func identity(_ op: ReduceOp, _ element: TMType, _ loc: SourceLoc) -> String {
        switch (op, element) {
        case (.add, .float(let width)):
            return width == 16 ? "0.0h" : "0.0f"
        case (.add, _):
            return "0"
        case (.max, .float):
            return "-INFINITY"
        case (.min, .float):
            return "INFINITY"
        case (.max, .integer(let width)):
            return width == 1 ? "false" : FunctionEmitter.integerBounds[width]?.min ?? "0"
        case (.min, .integer(let width)):
            return width == 1 ? "true" : FunctionEmitter.integerBounds[width]?.max ?? "0"
        default:
            return "0"
        }
    }

    private static let integerBounds: [Int: (min: String, max: String)] = [
        8: ("(-128)", "127"),
        16: ("(-32768)", "32767"),
        32: ("(-2147483647 - 1)", "2147483647"),
        64: ("(-9223372036854775807L - 1)", "9223372036854775807L"),
    ]

    private mutating func requireSimdCount() {
        guard !declaredSimdCount else { return }
        declaredSimdCount = true
        usesSimdgroups = true
        preamble.append(.line("uint tm_simd_count = (tm_threadgroup_size.x + 31u) / 32u;"))
    }

    // MARK: - tt.dot

    /// Metal's simdgroup matrices are 8x8, so every tile is padded up to whole
    /// fragments and the padding is zero-filled during staging.
    private static let fragment = 8

    /// Rounds a tile extent up to whole fragments — or, along a register-blocked
    /// dimension, up to a whole *block* of fragments, so that the last simdgroup's
    /// block never addresses a fragment the tile does not have.
    private static func padded(_ extent: Int, to granularity: Int = fragment) -> Int {
        (extent + granularity - 1) / granularity * granularity
    }

    private mutating func allocateTile(
        _ prefix: String, element: TMType, rows: Int, columns: Int, rowAxis: Int, columnAxis: Int,
        rowGranularity: Int = fragment, columnGranularity: Int = fragment, capacity: Int = 0,
        intoArena: Bool = false, intoSharedArena: Bool = false, _ loc: SourceLoc
    ) throws -> Tile {
        let paddedColumns = FunctionEmitter.padded(columns, to: columnGranularity)
        let tile = Tile(
            name: "tm_\(prefix)\(tileCount)", element: element, rows: rows, columns: columns,
            paddedRows: FunctionEmitter.padded(rows, to: rowGranularity),
            paddedColumns: paddedColumns,
            rowPadding: FunctionEmitter.rowPadding(paddedColumns, element, options),
            rowAxis: rowAxis, columnAxis: columnAxis)
        tileCount += 1
        let elementName = try scalarTypeName(element, loc)
        let shape = "\(tile.paddedRows)x\(tile.paddedColumns)"

        // An operand tile staged inside a register-resident accumulator's loop
        // does not need storage of its own: the accumulator's is free for exactly
        // as long as the contraction runs (see `stagingArena`).
        if intoArena, let arena = stagingArena {
            let slots = FunctionEmitter.arenaSlots(tile.elementCount, of: element, in: arena.element)
            let buffers = options.dotDoubleBuffer ? 2 : 1
            guard arena.cursor + slots * buffers <= arena.capacity else {
                throw CoreError.lowering(
                    "kernel '\(function.name)' cannot stage its tt.dot operand tiles inside the "
                        + "accumulator's \(arena.capacity)-slot arena", loc)
            }
            func pointer(_ offset: Int) -> String {
                let base = offset == 0 ? arena.name : "\(arena.name) + \(offset)"
                return element == arena.element
                    ? base : "(threadgroup \(elementName) *)(\(base))"
            }
            // Double buffering makes the tile a *variable* pointer that ping-pongs
            // between two halves of the arena at the end of each contraction step.
            let note = buffers == 2 ? "  // \(shape), double-buffered" : "  // \(shape)"
            preamble.append(
                .line(
                    "threadgroup \(elementName) *\(tile.name) = \(pointer(arena.cursor));\(note)"))
            if buffers == 2 {
                preamble.append(
                    .line(
                        "threadgroup \(elementName) *\(tile.name)_next = "
                            + "\(pointer(arena.cursor + slots));"))
                pingPongTiles.append((name: tile.name, element: elementName))
            }
            stagingArena?.cursor += slots * buffers
            return tile
        }

        // The kernel-wide operand arena: two dots' operand tiles are separated by
        // a barrier and never live at once, so they share storage. FlashAttention
        // stages four operand tiles (Q, K^T, P, V) per iteration and does not fit
        // in Metal's 32KB otherwise.
        if intoSharedArena, let arena = sharedArena {
            let slots = FunctionEmitter.arenaSlots(tile.elementCount, of: element, in: arena.element)
            guard sharedArenaCursor + slots <= arena.capacity else {
                throw CoreError.lowering(
                    "kernel '\(function.name)' cannot stage its tt.dot operand tiles inside the "
                        + "shared \(arena.capacity)-slot arena", loc)
            }
            if !sharedArenaDeclared {
                sharedArenaDeclared = true
                threadgroupBytes += arena.capacity * (arena.element.scalarByteWidth ?? 4)
                guard threadgroupBytes <= FunctionEmitter.threadgroupMemoryLimit else {
                    throw CoreError.lowering(
                        "kernel '\(function.name)' needs \(threadgroupBytes) bytes of threadgroup "
                            + "memory to stage its tt.dot tiles, over Metal's "
                            + "\(FunctionEmitter.threadgroupMemoryLimit)-byte limit; reduce "
                            + "BLOCK_M, BLOCK_N or HEAD_DIM", loc)
                }
                preamble.append(
                    .line(
                        "threadgroup \(try scalarTypeName(arena.element, loc)) "
                            + "\(arena.name)[\(arena.capacity)];  // shared tt.dot operand arena"))
            }
            let base = sharedArenaCursor == 0 ? arena.name : "\(arena.name) + \(sharedArenaCursor)"
            let pointer = element == arena.element ? base : "(threadgroup \(elementName) *)(\(base))"
            preamble.append(
                .line("threadgroup \(elementName) *\(tile.name) = \(pointer);  // \(shape)"))
            sharedArenaCursor += slots
            return tile
        }

        let slots = max(capacity, tile.elementCount)
        threadgroupBytes += slots * (element.scalarByteWidth ?? 4)
        guard threadgroupBytes <= FunctionEmitter.threadgroupMemoryLimit else {
            throw CoreError.lowering(
                "kernel '\(function.name)' needs \(threadgroupBytes) bytes of threadgroup memory "
                    + "to stage its tt.dot tiles, over Metal's "
                    + "\(FunctionEmitter.threadgroupMemoryLimit)-byte limit; reduce BLOCK_M, "
                    + "BLOCK_N or BLOCK_K", loc)
        }
        let note = slots > tile.elementCount
            ? "  // \(shape) accumulator; also the arena its operand tiles stage into"
            : "  // \(shape)"
        preamble.append(.line("threadgroup \(elementName) \(tile.name)[\(slots)];\(note)"))
        return tile
    }

    /// Slack after each row of a tile, in elements.
    ///
    /// Threadgroup memory is banked in 4-byte words, so a leading dimension that
    /// is a multiple of the bank count puts a whole column of the tile in one
    /// bank — and a fragment `simdgroup_load` reads a column of eight. One
    /// fragment's worth of slack skews the rows across banks instead. It is
    /// deliberately a knob rather than a certainty: whether it pays depends on how
    /// Apple's hardware actually banks threadgroup memory, which is not
    /// documented, so `tmbench` sweeps it.
    static func rowPadding(_ paddedColumns: Int, _ element: TMType, _ options: MetalCompiler.Options)
        -> Int
    {
        if options.dotTilePadding >= 0 { return options.dotTilePadding }
        // Off by default. It is not free — the slack comes out of the same 32KB
        // budget that decides how large a block shape can be — and on Apple
        // silicon it measured as a straight loss (docs/ARCHITECTURE.md
        // §Matmul throughput), so the emitter only pads when asked.
        _ = paddedColumns
        _ = element
        return 0
    }

    /// How many arena slots a tile of `count` elements needs when the arena is
    /// made of a possibly wider type.
    private static func arenaSlots(_ count: Int, of element: TMType, in arena: TMType) -> Int {
        let width = element.scalarByteWidth ?? 4
        let slot = arena.scalarByteWidth ?? 4
        return (count * width + slot - 1) / slot
    }

    /// Exposes a tile as an ordinary tensor value: reads of it index the tile,
    /// which puts every consumer back on the normal per-lane path.
    private mutating func registerTile(_ ssa: String, _ tile: Tile, type: TMType) {
        tiles[ssa] = tile
        names[ssa] = tile.expression
        types[ssa] = type
        // A tile reads as an ordinary per-lane value wherever its own axes' loops
        // are open, which is the nest the layout put the value in.
        let path = layout.path(of: ssa)
        levels[ssa] = path.isEmpty ? tile.axes.sorted() : path
    }

    /// The instructions needed to rebuild `ssa` inside a staging loop, in program
    /// order. Values that are already in scope at the uniform level stop the walk.
    private func recomputationOrder(
        for ssa: String, available: Set<Int> = [], _ loc: SourceLoc
    ) throws -> [Instruction] {
        func inScope(_ value: String) -> Bool {
            names[value] != nil && (levels[value] ?? []).isEmpty && tiles[value] == nil
        }

        var needed: Set<String> = []
        var stack = [ssa]
        while let value = stack.popLast() {
            if needed.contains(value) || inScope(value) { continue }
            // A value already in a threadgroup tile is *read* here rather than
            // rebuilt — which is what lets a dot take another dot's result (or a
            // spilled reduction, or a loop-carried tensor) as an operand, as long
            // as this nest has the loops its index expression needs.
            if let tile = tiles[value] {
                guard Set(tile.axes).isSubset(of: available) else {
                    throw CoreError.lowering(
                        "'%\(value)' lives in threadgroup memory indexed by block dimensions "
                            + "\(tile.axes), which this tt.dot's staging loops (\(available.sorted())) "
                            + "do not walk; a dot operand can only read a tile whose axes its own "
                            + "tile shares", loc)
                }
                continue
            }
            guard let instruction = definitions[value] else {
                throw CoreError.lowering(
                    "cannot rebuild '%\(value)' inside a tt.dot's staging loops: nothing in this "
                        + "kernel defines it as a pure operation", loc)
            }
            switch instruction.kind {
            case .forLoop, .ifOp, .reduce, .dot:
                throw CoreError.lowering(
                    "'%\(value)' feeds a tt.dot operand but is produced by "
                        + "\(instruction.mnemonic); a dot operand is rebuilt inside the dot's own "
                        + "loops, so only pure elementwise operations can produce one", loc)
            default:
                break
            }
            needed.insert(value)
            stack.append(contentsOf: instruction.kind.operandNames)
        }
        return
            needed
            .sorted { (valueOrder[$0] ?? 0) < (valueOrder[$1] ?? 0) }
            .compactMap { definitions[$0] }
    }

    /// Which of a rebuilt value's dimensions actually vary, propagated forward
    /// through the staging subgraph. `tt.make_range` is the only source of
    /// variation; splats and dense constants are uniform, and everything else
    /// inherits the union of its operands'.
    ///
    /// This is what lets the row-invariant half of a tile's address arithmetic —
    /// `offs_m * stride_am`, the row mask — sit in the outer staging loop instead
    /// of being redone for every element.
    private func stagingVariance(_ producers: [Instruction]) -> [String: Set<Int>] {
        var varying: [String: Set<Int>] = [:]
        // A value the walk stopped at because it is already in a tile varies
        // along that tile's axes — `acc * alpha[:, None]` reads the accumulator
        // tile, which varies along the column the staging loop strides.
        for instruction in producers {
            for operand in instruction.kind.operandNames where varying[operand] == nil {
                if let tile = tiles[operand] { varying[operand] = Set(tile.axes) }
            }
        }
        for instruction in producers {
            guard let result = FunctionEmitter.soleResult(instruction.kind) else { continue }
            var axes: Set<Int> = []
            switch instruction.kind {
            case .constant, .splat:
                break
            case .makeRange(let range, let type, _, _):
                if (type.shape?.first ?? 1) > 1, let axis = layout.axes[range]?.first {
                    axes.insert(axis)
                }
            default:
                for operand in instruction.kind.operandNames {
                    axes.formUnion(varying[operand] ?? [])
                }
            }
            varying[result] = axes
        }
        return varying
    }

    /// What a run of consecutive columns has to look like before its four scalar
    /// device loads may be replaced by one vector load.
    private struct VectorStagingPlan {
        /// The `tt.load` being vectorised, and its operands.
        var pointer: String
        var mask: String?
        /// Producers to replay when evaluating the *mask* at one column. Small —
        /// a couple of comparisons — which is what makes the run-level guard
        /// cheap enough to be worth having.
        var maskSlice: [Instruction]
        /// The address's column stride, as a tree over SSA values. One element is
        /// what a vector load needs, and it is a runtime fact.
        var stride: Coefficient
    }

    /// The coefficient of the column index in a staged address, symbolically.
    /// Rendered to MSL once the values it names have been emitted.
    private indirect enum Coefficient {
        case literal(Int)
        case value(String)
        case sum(Coefficient, Coefficient)
        case difference(Coefficient, Coefficient)
        case product(Coefficient, Coefficient)

        var isZero: Bool {
            if case .literal(0) = self { return true }
            return false
        }
    }

    /// Decides whether a staged value is one masked load per column of a run
    /// whose addresses are affine in the column index — the only shape a vector
    /// load can serve.
    ///
    /// Two properties have to hold, and only one of them is decidable here.
    /// *Affinity* is: the address is `p0 + c * stride` for some column-invariant
    /// `stride`, which follows structurally from the staging subgraph (a closed
    /// set — `tt.make_range`, `tt.splat`, `arith.addi/muli`, `tt.addptr`) and is
    /// what makes checking the two endpoints of a run sufficient. *Unit stride*
    /// and *alignment* are runtime facts about the kernel's arguments, so they
    /// become a runtime test and both paths are emitted (see `stage`).
    ///
    /// The mask is required to be monotone in the column index — a conjunction of
    /// `<`/`<=` against a column-invariant bound, with a literal positive
    /// coefficient on the varying side — so that the mask at the *last* column of
    /// the run implies the mask at all four. That is exactly the shape Triton's
    /// `offs < N` guards have.
    private func vectorStagingPlan(
        for ssa: String, producers: [Instruction], varying: [String: Set<Int>], tile: Tile,
        _ loc: SourceLoc
    ) -> VectorStagingPlan? {
        guard options.dotVectorStaging, tile.columns % 4 == 0,
            let width = tile.element.scalarByteWidth, width == 4 || width == 2
        else { return nil }
        // Exactly one load, and it is the staged value itself.
        var load: OpKind?
        var loads = 0
        for instruction in producers {
            guard case .load(let result, _, _, _) = instruction.kind else { continue }
            loads += 1
            if result == ssa { load = instruction.kind }
        }
        guard loads == 1, case .load(_, let pointer, let mask, _) = load else { return nil }

        let column = tile.columnAxis
        var affinity: [String: Coefficient] = [:]
        /// `nil` means "not affine in the column index".
        func known(_ value: String) -> Coefficient? {
            if let recorded = affinity[value] { return recorded }
            // Anything outside the subgraph is already in scope at the uniform
            // level, so it cannot vary with the column.
            let axes = varying[value] ?? Set(tiles[value]?.axes ?? [])
            return axes.contains(column) ? nil : .literal(0)
        }
        for instruction in producers {
            guard let result = FunctionEmitter.soleResult(instruction.kind) else { continue }
            guard (varying[result] ?? []).contains(column) else {
                affinity[result] = .literal(0)
                continue
            }
            switch instruction.kind {
            case .makeRange:
                affinity[result] = .literal(1)
            case .intBinary(_, let op, let lhs, let rhs):
                guard let a = known(lhs), let b = known(rhs) else { break }
                switch op {
                case .add:
                    affinity[result] = a.isZero ? b : (b.isZero ? a : .sum(a, b))
                case .sub:
                    affinity[result] = b.isZero ? a : .difference(a, b)
                case .mul:
                    // A product is affine only if one side is column-invariant;
                    // then the coefficient is scaled by that side's runtime value.
                    if a.isZero { affinity[result] = .product(.value(lhs), b) }
                    else if b.isZero { affinity[result] = .product(a, .value(rhs)) }
                default: break
                }
            case .addPtr(_, let pointer, let offset):
                guard let base = known(pointer), let delta = known(offset) else { break }
                affinity[result] = base.isZero ? delta : (delta.isZero ? base : .sum(base, delta))
            case .cast(_, let op, let source, _) where op == .extsi || op == .extui:
                affinity[result] = known(source)
            case .expandDims(_, _, let source, _), .broadcast(_, _, let source):
                affinity[result] = known(source)
            default:
                break
            }
        }

        // The address has to be affine in the column, or the run is not four
        // consecutive elements of anything and the endpoint reasoning below says
        // nothing about the columns in between.
        guard let stride = known(pointer) else { return nil }

        /// A mask that can only go from true to false as the column grows, so
        /// that its value at the *last* column of a run covers the whole run.
        func monotone(_ value: String) -> Bool {
            guard (varying[value] ?? []).contains(column) else { return true }
            guard let instruction = producers.first(where: {
                FunctionEmitter.soleResult($0.kind) == value
            }) else { return false }
            switch instruction.kind {
            case .intBinary(_, .and, let lhs, let rhs):
                return monotone(lhs) && monotone(rhs)
            case .intCompare(_, let predicate, let lhs, let rhs):
                guard ["slt", "sle", "ult", "ule"].contains(predicate) else { return false }
                guard known(rhs)?.isZero == true else { return false }
                // Only a *literal positive* coefficient proves the direction; a
                // runtime stride could be negative.
                if case .literal(let coefficient) = known(lhs), coefficient > 0 { return true }
                return false
            case .expandDims(_, _, let source, _), .broadcast(_, _, let source):
                return monotone(source)
            default:
                return false
            }
        }
        if let mask, !monotone(mask) { return nil }

        let slice = (try? mask.map { try recomputationOrder(for: $0, available: Set(tile.axes), loc) })
        return VectorStagingPlan(
            pointer: pointer, mask: mask, maskSlice: slice.flatMap { $0 } ?? [], stride: stride)
    }

    /// The MSL for a column stride, once the values it names have been emitted.
    private func render(_ coefficient: Coefficient) -> String? {
        switch coefficient {
        case .literal(let value): return "\(value)"
        case .value(let ssa): return names[ssa]
        case .sum(let a, let b):
            guard let a = render(a), let b = render(b) else { return nil }
            return "(\(a) + \(b))"
        case .difference(let a, let b):
            guard let a = render(a), let b = render(b) else { return nil }
            return "(\(a) - \(b))"
        case .product(let a, let b):
            guard let a = render(a), let b = render(b) else { return nil }
            return "(\(a) * \(b))"
        }
    }

    /// Writes one tensor value into a threadgroup tile.
    ///
    /// The tile's own two dimensions become the loop nest — outer uniform, inner
    /// strided across the threadgroup — and the value's producers are rebuilt
    /// inside it, each at the shallower of the two loops it can live in. Padding
    /// lanes take a zero without evaluating any pointer arithmetic, so an edge
    /// tile never forms an out-of-range address.
    private mutating func stage(_ ssa: String, into tile: Tile, _ loc: SourceLoc) throws -> Stmt {
        let producers = try recomputationOrder(for: ssa, available: Set(tile.axes), loc)
        let varying = stagingVariance(producers)
        let elementName = try scalarTypeName(tile.element, loc)
        let zero = literal(
            tile.element.isFloatLike ? .float(0) : .integer(0), tile.element, loc)

        let savedNames = names
        let savedTypes = types
        let savedLevels = levels
        let savedTarget = stagingTargetFrame
        stagingDepth += 1
        defer {
            stagingDepth -= 1
            stagingTargetFrame = savedTarget
            names = savedNames
            types = savedTypes
            levels = savedLevels
        }

        let outerFrame = frames.count
        let row = "tm_i\(tile.rowAxis)"
        let column = "tm_i\(tile.columnAxis)"
        // The threadgroup is spread over *both* tile dimensions, not just the
        // innermost one as an elementwise loop is: a `BLOCK_M x BLOCK_K` tile is
        // usually much narrower than the threadgroup, and striding only its
        // columns would leave most threads with nothing to stage. `lanes`
        // consecutive threads take consecutive columns, which keeps the device
        // reads coalesced; the rest walk the rows.
        //
        // Each thread takes a *run* of `unroll` consecutive columns rather than a
        // single one. Every element of a staged tile costs a masked device load
        // plus its share of the address arithmetic, and with one column per
        // thread none of that arithmetic is shared: the row half is recomputed
        // for every element even though it is loop-invariant, and the column half
        // cannot be strength-reduced because there is no loop to reduce along.
        // Giving a thread a contiguous run fixes both — the row half is computed
        // once for the run, and the column half becomes a constant-trip-count
        // loop that Metal's compiler unrolls and reassociates into a pointer
        // increment. This is the cheap-staging item from
        // docs/ARCHITECTURE.md §Matmul throughput.
        //
        // The row stride is the *literal* thread count, not `tm_threadgroup_size`:
        // a kernel containing a `tt.dot` must already be launched at the reported
        // `threads_per_threadgroup` (§Execution model), and spelling it out gives
        // every staging loop a compile-time trip count for Metal's own optimiser
        // to unroll and strength-reduce.
        let unroll = stagingUnroll(tile)
        let lanes = min(tile.paddedColumns / unroll, threadsPerThreadgroup)
        /// True once the run's vector fast path has opened an `else` around the
        /// per-element loop, which is then one more frame to close.
        var vectorElse = false
        frames.append(
            Frame(
                path: [], kind: .staging,
                open: "for (uint \(row) = tm_thread_id.x / \(lanes)u; \(row) < \(tile.paddedRows)u; "
                    + "\(row) += \(max(1, threadsPerThreadgroup / lanes))u) {"))
        if unroll > 1 {
            let group = "\(column)_run"
            frames.append(
                Frame(
                    path: [], kind: .staging,
                    open: "for (uint \(group) = (tm_thread_id.x % \(lanes)u) * \(unroll)u; "
                        + "\(group) < \(tile.paddedColumns)u; \(group) += \(lanes * unroll)u) {"))
            // The run's four loads become one, when the run turns out at runtime
            // to be contiguous, aligned and entirely inside the mask. Everything
            // that decides that is evaluated here, once per run, from the two
            // endpoints of the run — which is sufficient because the plan already
            // established that the address is affine in the column index.
            if let plan = vectorStagingPlan(
                for: ssa, producers: producers, varying: varying, tile: tile, loc), unroll == 4
            {
                let ok = "\(tile.name)_vok"
                let base = "\(tile.name)_vbase"
                let runFrame = frames.count - 1

                // A run that reaches outside the tile's logical extent is not a
                // candidate, and — like the per-element path — must not so much as
                // form an address there, which is why this guards the rebuilds
                // below rather than only the load.
                var conditions: [String] = []
                if tile.paddedColumns != tile.columns {
                    conditions.append("\(group) + 4u <= \(tile.columns)u")
                }
                if tile.paddedRows != tile.rows { conditions.append("\(row) < \(tile.rows)u") }

                /// Rebuilds a slice of the staging subgraph at one column of the
                /// run, inside a scope of its own so its names do not collide
                /// with the per-element loop's.
                func replay(
                    _ slice: [Instruction], at offset: Int, _ trailing: (String) -> Stmt,
                    of value: String
                ) throws -> TMType? {
                    frames.append(
                        Frame(
                            path: [], kind: .staging,
                            open: conditions.isEmpty ? "{" : "if (\(ok)) {"))
                    let scope = frames.count - 1
                    frames[scope].statements.append(
                        .line(
                            "uint \(column) = \(group)\(offset == 0 ? "" : " + \(offset)u");"))
                    let outerNames = names
                    let outerTypes = types
                    let outerLevels = levels
                    defer {
                        names = outerNames
                        types = outerTypes
                        levels = outerLevels
                    }
                    for instruction in slice {
                        stagingTargetFrame = scope
                        try emit(instruction)
                    }
                    frames[scope].statements.append(trailing(try name(of: value, loc)))
                    let resolved = types[value]
                    closeTopFrame()
                    return resolved
                }

                // The run's address, evaluated once instead of once per element.
                // Everything else follows from it: whether consecutive columns are
                // one element apart, and whether the address is aligned for a
                // vector load.
                var stride: String?
                let addressSlice = try recomputationOrder(for: plan.pointer, available: Set(tile.axes), loc)
                let pointerType = try replay(addressSlice, at: 0, { address in
                    stride = render(plan.stride)
                    return .line("\(base) = \(address);")
                }, of: plan.pointer)

                if let pointerType, case .pointer(let pointee) = pointerType.scalarized,
                    let stride, let width = pointee.scalarByteWidth, width == 4 || width == 2
                {
                    frames[runFrame].statements.insert(
                        contentsOf: [
                            Stmt.line(
                                "bool \(ok) = "
                                    + (conditions.isEmpty
                                        ? "true;" : conditions.joined(separator: " && ") + ";")),
                            Stmt.line("\(try declaration(pointerType.scalarized, base, loc));"),
                        ], at: 0)
                    // The mask at the run's *last* column covers the whole run,
                    // because the plan established that it is monotone.
                    if let mask = plan.mask {
                        _ = try replay(plan.maskSlice, at: 3, { value in
                            .line("\(ok) = \(ok) && \(value);")
                        }, of: mask)
                    }
                    frames[runFrame].statements.append(
                        .line(
                            "\(ok) = \(ok) && \(stride) == 1 && "
                                + "(((uintptr_t)\(base) & \(width * 4 - 1)u) == 0u);"))

                    // The fast path: one vector load, four tile writes, and none
                    // of the per-element address arithmetic the loop below does.
                    let scalar = try scalarTypeName(pointee, loc)
                    let vector = "\(tile.name)_vec"
                    var fast: [Stmt] = [
                        .line("\(scalar)4 \(vector) = *(device const \(scalar)4 *)(\(base));")
                    ]
                    for lane in 0..<4 {
                        let slot = "\(tile.name)[\(row) * \(tile.stride)u + \(group) + \(lane)u]"
                        let element = "\(vector)[\(lane)u]"
                        fast.append(
                            .line(
                                "\(slot) = "
                                    + (pointee == tile.element
                                        ? element : "\(elementName)(\(element))") + ";"))
                    }
                    frames[runFrame].statements.append(
                        .group(
                            open: "if (\(ok)) {  // one vector load for the whole run",
                            body: fast, close: "}"))
                    frames.append(Frame(path: [], kind: .staging, open: "else {"))
                    vectorElse = true
                }
            }
            frames.append(
                Frame(
                    path: [], kind: .staging,
                    open: "for (uint \(column) = \(group); \(column) < \(group) + \(unroll)u; "
                        + "++\(column)) {"))
        } else {
            frames.append(
                Frame(
                    path: [], kind: .staging,
                    open: "for (uint \(column) = tm_thread_id.x % \(lanes)u; "
                        + "\(column) < \(tile.paddedColumns)u; \(column) += \(lanes)u) {"))
        }

        var guarded = false
        let temporary = "tm_staged"
        if tile.needsPadding {
            var conditions: [String] = []
            if tile.paddedRows != tile.rows { conditions.append("\(row) < \(tile.rows)u") }
            if tile.paddedColumns != tile.columns {
                conditions.append("\(column) < \(tile.columns)u")
            }
            frames[frames.count - 1].statements.append(
                .line("\(elementName) \(temporary) = \(zero);  // 8x8 fragment padding"))
            frames.append(
                Frame(
                    path: [], kind: .staging,
                    open: "if (\(conditions.joined(separator: " && "))) {"))
            guarded = true
        }
        let innerFrame = frames.count - 1

        for instruction in producers {
            // A load always goes inside the padding guard, so an edge lane never
            // dereferences an address it had no business forming.
            var dereferences = false
            if case .load = instruction.kind { dereferences = true }
            let axes = FunctionEmitter.soleResult(instruction.kind).flatMap { varying[$0] } ?? []
            stagingTargetFrame =
                dereferences || axes.contains(tile.columnAxis) ? innerFrame : outerFrame
            try emit(instruction)
        }
        stagingTargetFrame = innerFrame

        let sourceType = try type(of: ssa, loc)
        var value = try name(of: ssa, loc)
        if sourceType.scalarized != tile.element {
            value = "\(elementName)(\(value))"
        }
        if guarded {
            frames[frames.count - 1].statements.append(.line("\(temporary) = \(value);"))
            closeTopFrame()
            frames[frames.count - 1].statements.append(.line("\(tile.slot) = \(temporary);"))
        } else {
            frames[frames.count - 1].statements.append(.line("\(tile.slot) = \(value);"))
        }
        closeTopFrame()
        if vectorElse { closeTopFrame() }
        if unroll > 1 { closeTopFrame() }

        let outer = frames.removeLast()
        return .group(open: outer.open, body: outer.statements, close: outer.close)
    }

    /// How many consecutive columns one thread stages.
    ///
    /// Bigger is cheaper per element but coarser: the tile is handed out in runs
    /// of this many columns, so too large a run leaves threads idle. The largest
    /// run that still keeps every thread busy wins, and a run has to divide the
    /// padded column count so that no iteration straddles the end of a row.
    private func stagingUnroll(_ tile: Tile) -> Int {
        if options.dotStagingUnroll > 0 {
            let requested = options.dotStagingUnroll
            return tile.paddedColumns % requested == 0 ? requested : 1
        }
        for candidate in [4, 2] where tile.paddedColumns % candidate == 0 {
            if tile.paddedRows * (tile.paddedColumns / candidate) >= threadsPerThreadgroup {
                return candidate
            }
        }
        return 1
    }

    private mutating func emitDot(_ dot: DotOp, loc: SourceLoc) throws {
        guard case .tensor(let lhsShape, let lhsElement) = dot.lhsType, lhsShape.count == 2,
            case .tensor(let rhsShape, let rhsElement) = dot.rhsType, rhsShape.count == 2,
            case .tensor(let resultShape, let resultElement) = dot.resultType,
            resultShape.count == 2
        else {
            throw CoreError.lowering(
                "tt.dot operates on rank-2 tensors, found \(dot.lhsType) * \(dot.rhsType) -> "
                    + "\(dot.resultType)", loc)
        }
        guard lhsShape[1] == rhsShape[0] else {
            throw CoreError.lowering(
                "tt.dot's contracted dimensions differ: \(dot.lhsType) * \(dot.rhsType)", loc)
        }
        guard resultShape == [lhsShape[0], rhsShape[1]] else {
            throw CoreError.lowering(
                "tt.dot result \(dot.resultType) does not match \(lhsShape[0])x\(rhsShape[1])", loc)
        }
        guard lhsElement == rhsElement else {
            throw CoreError.lowering(
                "tt.dot operands have different element types: \(lhsElement) and \(rhsElement)",
                loc)
        }
        for element in [lhsElement, resultElement] {
            guard element == .float(width: 16) || element == .float(width: 32) else {
                throw CoreError.unsupportedOp(
                    "tt.dot on \(element) (Metal's simdgroup matrices are half or float)", loc)
            }
        }
        guard resultElement != .float(width: 16) || lhsElement == .float(width: 16) else {
            throw CoreError.lowering(
                "tt.dot cannot accumulate f32 operands into an f16 result", loc)
        }
        // A deferred accumulator (the usual `dense<0.0>` seed) has no type here
        // yet — it is rebuilt inside the staging loops below.
        if let accumulatorType = types[dot.accumulator] {
            guard accumulatorType.scalarized == resultElement,
                accumulatorType.shape == resultShape
            else {
                throw CoreError.lowering(
                    "tt.dot's accumulator is \(accumulatorType) but its result is "
                        + "\(dot.resultType)", loc)
            }
        }

        // Which block axis each of the six operand dimensions indexes. These are
        // *not* (0, 1, contraction) in general: FA-2's second dot contracts over
        // the same axis its softmax iterates and produces the head dimension its
        // accumulator iterates, so all three come from the layout.
        let lhsAxes = layout.axes[dot.lhs] ?? [0, rank]
        let rhsAxes = layout.axes[dot.rhs] ?? [rank, 1]
        let resultAxes = layout.axes[dot.result] ?? [0, 1]
        let level = uniformLevel
        guard frames.last(where: { $0.kind == .region }) == nil else {
            throw CoreError.lowering(
                "tt.dot inside a per-lane scf region is not lowered: its threadgroup barriers "
                    + "have to be reached by every thread", loc)
        }
        try ensureLevel(level, loc)

        let index = dotCount
        dotCount += 1
        usesSimdgroups = true

        // Three cases for the accumulator, in descending order of how good they
        // are: an `scf.for` already put it in registers for the whole contraction
        // (§Cross-lane regions), an `scf.for` gave it a tile but not registers, or
        // a stand-alone dot has to stage its per-lane accumulator in first.
        var statements: [Stmt] = []
        let accumulator: Tile
        let registers: AccumulatorRegisters
        let resident: Bool
        /// A stand-alone dot seeded with `dense<0.0>`: no staging pass, no load.
        var zeroed = false
        if let existing = tiles[dot.accumulator] {
            accumulator = existing
            if let held = residentAccumulators[existing.name] {
                registers = held
                resident = true
            } else {
                registers = self.registers(index, for: existing, element: resultElement)
                resident = false
            }
        } else if let bound = boundAccumulators[dot.result] {
            // A cross-lane loop carries this accumulator, but the loop does not
            // yield the dot's result directly — FA-2 rescales `acc` by a per-row
            // correction factor first. The carried tile *is* the dot's
            // accumulator tile, and the rescale is lowered as the staging pass
            // that fills it: each thread reads and writes the same element, so
            // the read-modify-write needs no more ordering than staging already
            // has (§Cross-lane regions).
            accumulator = bound
            registers = self.registers(index, for: bound, element: resultElement)
            resident = false
            statements.append(
                .line("// tt.dot: the carried accumulator, rescaled in place"))
            statements.append(try stage(dot.accumulator, into: bound, loc))
        } else {
            let blocking = self.blocking(rows: resultShape[0], columns: resultShape[1])
            accumulator = try allocateTile(
                "dot_c", element: resultElement, rows: resultShape[0], columns: resultShape[1],
                rowAxis: resultAxes[0], columnAxis: resultAxes[1],
                rowGranularity: blocking.tilesM * FunctionEmitter.fragment,
                columnGranularity: blocking.tilesN * FunctionEmitter.fragment, loc)
            registers = self.registers(index, for: accumulator, element: resultElement)
            resident = false
            zeroed = isZeroSplat(dot.accumulator)
            if !zeroed { statements.append(try stage(dot.accumulator, into: accumulator, loc)) }
        }

        // A and B are padded to the same block granularity as the accumulator so
        // that the last block's fragments address rows and columns the tiles
        // actually have.
        let blocking = registers.blocking
        let shared = sharesOperandArena
        if shared {
            sharedArenaCursor = 0
            if sharedArena == nil {
                sharedArena = (
                    name: "tm_dot_arena", element: .float(width: 32),
                    capacity: sharedArenaSlots(function.body))
            }
        }
        let lhs = try allocateTile(
            "dot_a", element: lhsElement, rows: lhsShape[0], columns: lhsShape[1],
            rowAxis: lhsAxes[0], columnAxis: lhsAxes[1],
            rowGranularity: blocking.tilesM * FunctionEmitter.fragment,
            intoArena: resident, intoSharedArena: shared, loc)
        let rhs = try allocateTile(
            "dot_b", element: rhsElement, rows: rhsShape[0], columns: rhsShape[1],
            rowAxis: rhsAxes[0], columnAxis: rhsAxes[1],
            columnGranularity: blocking.tilesN * FunctionEmitter.fragment,
            intoArena: resident, intoSharedArena: shared, loc)

        // Everything staged below may read a tile ordinary per-lane code wrote
        // (a spilled reduction, a carried accumulator), and those writes are in
        // whatever nest computed them.
        if hasSpilledTiles {
            statements.insert(.line("threadgroup_barrier(mem_flags::mem_threadgroup);"), at: 0)
        }
        statements.append(.line("// tt.dot: stage A (\(lhsShape[0])x\(lhsShape[1]))"))
        statements.append(try stage(dot.lhs, into: lhs, loc))
        statements.append(.line("// tt.dot: stage B (\(rhsShape[0])x\(rhsShape[1]))"))
        statements.append(try stage(dot.rhs, into: rhs, loc))
        statements.append(.line("threadgroup_barrier(mem_flags::mem_threadgroup);"))
        // When the accumulator is resident the fragments were loaded before the
        // contraction loop and are stored back after it, so all that happens here
        // is arithmetic.
        if !resident {
            statements.append(contentsOf: loadAccumulator(registers, zeroed: zeroed))
        }
        statements.append(contentsOf: accumulateSteps(index, lhs, rhs, registers))
        if !resident { statements.append(contentsOf: storeAccumulator(registers)) }
        // The trailing barrier exists so the next contraction step's staging
        // cannot overwrite a tile this one is still reading. With two buffers it
        // writes the other half instead, and the barrier above already orders it
        // after the previous step's arithmetic.
        if !options.dotDoubleBuffer || !resident {
            statements.append(.line("threadgroup_barrier(mem_flags::mem_threadgroup);"))
        }

        for statement in statements {
            try append(
                statement, level: level, recomputable: false,
                reason: "a tt.dot writes threadgroup memory and cannot be recomputed", loc)
        }
        registerTile(dot.result, accumulator, type: dot.resultType)
    }

    // MARK: Register-blocked fragment arithmetic

    /// The blocking for an `MxN` accumulator on this kernel's threadgroup.
    private func blocking(rows: Int, columns: Int) -> RegisterBlocking {
        FunctionEmitter.registerBlocking(
            rowFragments: FunctionEmitter.padded(rows) / FunctionEmitter.fragment,
            columnFragments: FunctionEmitter.padded(columns) / FunctionEmitter.fragment,
            simdgroups: simdgroupCount,
            requestedM: options.dotRegisterM, requestedN: options.dotRegisterN)
    }

    /// True when this kernel's `tt.dot`s share one operand arena rather than each
    /// declaring its own tiles.
    ///
    /// Only with more than one dot, and only when no accumulator is
    /// register-resident (a resident accumulator's own tile is already the arena
    /// and is the better deal — it costs nothing at all). Two dots' operand tiles
    /// are never live at once: the barrier that ends one dot's arithmetic is
    /// before the next one's staging.
    private var sharesOperandArena: Bool { dotTotal >= 2 && stagingArena == nil }

    /// The largest operand footprint of any single `tt.dot` in `body`, in f32
    /// slots — what the shared arena has to be.
    private func sharedArenaSlots(_ body: [Instruction]) -> Int {
        var largest = 0
        func walk(_ body: [Instruction]) {
            for instruction in body {
                switch instruction.kind {
                case .forLoop(let loop): walk(loop.body)
                case .ifOp(let branch):
                    walk(branch.thenBody)
                    walk(branch.elseBody)
                case .dot(let dot):
                    guard case .tensor(let lhsShape, let lhsElement) = dot.lhsType,
                        case .tensor(let rhsShape, let rhsElement) = dot.rhsType,
                        case .tensor(let resultShape, _) = dot.resultType, resultShape.count == 2
                    else { continue }
                    let size = FunctionEmitter.fragment
                    let blocking = self.blocking(rows: resultShape[0], columns: resultShape[1])
                    func count(_ rows: Int, _ columns: Int, _ element: TMType) -> Int {
                        rows * (columns + FunctionEmitter.rowPadding(columns, element, options))
                    }
                    let lhs = count(
                        FunctionEmitter.padded(lhsShape[0], to: blocking.tilesM * size),
                        FunctionEmitter.padded(lhsShape[1]), lhsElement)
                    let rhs = count(
                        FunctionEmitter.padded(rhsShape[0]),
                        FunctionEmitter.padded(rhsShape[1], to: blocking.tilesN * size), rhsElement)
                    let slots =
                        FunctionEmitter.arenaSlots(lhs, of: lhsElement, in: .float(width: 32))
                        + FunctionEmitter.arenaSlots(rhs, of: rhsElement, in: .float(width: 32))
                    largest = max(largest, slots)
                default: continue
                }
            }
        }
        walk(body)
        return largest
    }

    /// How much arena the operand tiles of every `tt.dot` in `body` need, in slots
    /// of the accumulator's element type. The accumulator's tile is sized to hold
    /// this as well as itself, since the two are never live at the same time.
    private func operandArenaSlots(
        _ body: [Instruction], blocking: RegisterBlocking, arena: TMType
    ) -> Int {
        var slots = 0
        for instruction in body {
            guard case .dot(let dot) = instruction.kind,
                case .tensor(let lhsShape, let lhsElement) = dot.lhsType, lhsShape.count == 2,
                case .tensor(let rhsShape, let rhsElement) = dot.rhsType, rhsShape.count == 2
            else { continue }
            let size = FunctionEmitter.fragment
            func count(_ rows: Int, _ columns: Int, _ element: TMType) -> Int {
                rows * (columns + FunctionEmitter.rowPadding(columns, element, options))
            }
            let lhsCount = count(
                FunctionEmitter.padded(lhsShape[0], to: blocking.tilesM * size),
                FunctionEmitter.padded(lhsShape[1]), lhsElement)
            let rhsCount = count(
                FunctionEmitter.padded(rhsShape[0]),
                FunctionEmitter.padded(rhsShape[1], to: blocking.tilesN * size), rhsElement)
            let buffers = options.dotDoubleBuffer ? 2 : 1
            slots += FunctionEmitter.arenaSlots(lhsCount, of: lhsElement, in: arena) * buffers
            slots += FunctionEmitter.arenaSlots(rhsCount, of: rhsElement, in: arena) * buffers
        }
        return slots
    }

    private func registers(_ index: Int, for tile: Tile, element: TMType) -> AccumulatorRegisters {
        let blocking = self.blocking(rows: tile.rows, columns: tile.columns)
        return AccumulatorRegisters(
            tile: tile, blocking: blocking,
            matrix: element == .float(width: 16) ? "simdgroup_half8x8" : "simdgroup_float8x8",
            prefix: "tm_acc\(index)",
            sharedColumns: FunctionEmitter.sharesColumns(blocking))
    }

    /// Whether every wave of a simdgroup lands in the same column of the block
    /// grid, which is true exactly when the grid's width divides the simdgroup
    /// count — `(s + w*S) % bN == s % bN` iff `bN | S`.
    static func sharesColumns(_ blocking: RegisterBlocking) -> Bool {
        blocking.blocksN <= blocking.simdgroups && blocking.simdgroups % blocking.blocksN == 0
    }

    /// Which `tilesM x tilesN` grid to give each simdgroup.
    ///
    /// The CUDA playbook says: as large as the registers allow, because
    /// `tilesM * tilesN` multiply-accumulates come off only `tilesM + tilesN`
    /// operand loads. **On M1-generation Apple silicon that is wrong**, and
    /// measurably so (M1 Max and M1 Pro; unmeasured on M2/M3/M4, whose memory
    /// hierarchy differs — re-run `tmbench --sweep full` before trusting this
    /// default there) — at
    /// `64x128` on 16 simdgroups, 1x1 blocking runs 28% faster than 2x2 with the
    /// same number of accumulator fragments per simdgroup, and at `64x64` the two
    /// are within noise (docs/ARCHITECTURE.md §Matmul throughput). The operand
    /// loads a bigger block saves are not on the critical path here, and the
    /// coarser fragment-to-simdgroup mapping it produces evidently is.
    ///
    /// So the default is the *smallest* blocking that fits, and what is actually
    /// being chosen is a fallback: when one fragment per simdgroup per wave would
    /// need more accumulator registers than a lane can hold, the block has to grow
    /// to cover the same output with fewer waves. Two things then decide between
    /// the candidates — occupancy (the last wave should not leave most simdgroups
    /// idle) and fit (a block that does not divide the fragment grid pads the tile
    /// out to whole blocks, costing memory and arithmetic on zeros).
    ///
    /// The autotuner overrides all of this; `tmbench --sweep full` sweeps it.
    static func registerBlocking(
        rowFragments: Int, columnFragments: Int, simdgroups: Int, requestedM: Int, requestedN: Int
    ) -> RegisterBlocking {
        func describe(_ tilesM: Int, _ tilesN: Int) -> RegisterBlocking {
            let blocksM = (rowFragments + tilesM - 1) / tilesM
            let blocksN = (columnFragments + tilesN - 1) / tilesN
            return RegisterBlocking(
                tilesM: tilesM, tilesN: tilesN, blocksM: blocksM, blocksN: blocksN,
                simdgroups: simdgroups,
                waves: (blocksM * blocksN + simdgroups - 1) / simdgroups)
        }
        guard requestedM <= 0, requestedN <= 0 else {
            return describe(
                max(1, min(requestedM, rowFragments)), max(1, min(requestedN, columnFragments)))
        }

        func fit(_ candidate: RegisterBlocking) -> Double {
            Double(rowFragments * columnFragments)
                / Double(
                    candidate.blocksM * candidate.tilesM * candidate.blocksN * candidate.tilesN)
        }
        func score(_ candidate: RegisterBlocking) -> Double {
            let occupancy = Double(candidate.blocks) / Double(candidate.waves * simdgroups)
            return occupancy * fit(candidate)
        }
        /// How to choose between blockings the score cannot separate, best first.
        ///
        /// Never widen along N: a block wider than one fragment puts a
        /// simdgroup's waves in different columns of the block grid, which is
        /// exactly what the shared-column mapping (and the single B load per
        /// step it buys) depends on — measured at 4327 GFLOP/s for 1x1 against
        /// 2836 for 2x2 at `64x128`. *Two* fragments along M, on the other hand,
        /// keeps the column and halves the waves, and at equal score that is
        /// worth a geometric mean of +4% across the swept shapes and +8% at the
        /// fastest one. Beyond two there is no measurement, so nothing is
        /// promoted past it and the smallest wins.
        func preference(_ candidate: RegisterBlocking) -> (Int, Int, Int) {
            (candidate.tilesN, candidate.tilesM == 2 ? 0 : 1, candidate.tilesM * candidate.tilesN)
        }

        var best: RegisterBlocking?
        for tilesM in blockingCandidates where tilesM <= rowFragments {
            for tilesN in blockingCandidates where tilesN <= columnFragments {
                let candidate = describe(tilesM, tilesN)
                guard candidate.fragmentsPerSimdgroup <= maxAccumulatorFragments else { continue }
                guard let incumbent = best else {
                    best = candidate
                    continue
                }
                let delta = score(candidate) - score(incumbent)
                let better: Bool
                if abs(delta) > 1e-9 {
                    better = delta > 0
                } else if preference(candidate) != preference(incumbent) {
                    better = preference(candidate) < preference(incumbent)
                } else {
                    better = fit(candidate) > fit(incumbent)
                }
                if better { best = candidate }
            }
        }
        // Every candidate needed more registers than a lane has: take the coarsest,
        // which is the one with the fewest fragments per simdgroup.
        return best ?? describe(min(8, rowFragments), min(8, columnFragments))
    }

    static let blockingCandidates = [1, 2, 4, 8]

    /// At most this many 8x8 accumulator fragments per simdgroup. One fragment is
    /// 64 floats spread over 32 lanes — two registers a lane — so 16 of them cost
    /// 32 registers, and the operand fragments feeding them live on top of that.
    static let maxAccumulatorFragments = 16

    /// Names each simdgroup's block of the output fragment grid and fills its
    /// registers from the accumulator tile.
    ///
    /// Emitted **once**, before the contraction loop when there is one, so the
    /// accumulator stops making a round trip through threadgroup memory on every
    /// K step. That was the second thing docs/ARCHITECTURE.md §Matmul throughput
    /// named.
    ///
    /// `zeroed` is the common case and the cheap one: an accumulator seeded with
    /// `arith.constant dense<0.0>` needs no prologue at all — no per-lane pass
    /// filling a tile with zeros, no `simdgroup_load` reading them back, and
    /// neither of the two barriers that ordered those against each other. The
    /// fragments are simply born zero in registers.
    private func loadAccumulator(_ registers: AccumulatorRegisters, zeroed: Bool = false) -> [Stmt]
    {
        let blocking = registers.blocking
        var statements: [Stmt] = [
            .line(
                "// tt.dot accumulator: \(blocking.summary)"
                    + (zeroed ? ", zero-initialised in registers" : ""))
        ]
        // When the block grid's width divides the simdgroup count, every wave of
        // a given simdgroup lands in the *same column* of the grid — `flat / bN`
        // and `flat % bN` decompose exactly — so the column index is emitted once
        // instead of once per wave. That is not cosmetic: it is what makes the B
        // fragment of a contraction step textually identical across waves, and
        // therefore loadable once (see `accumulateSteps`).
        if registers.sharedColumns {
            let column: String
            switch blocking.blocksN {
            case 1: column = "0u"
            case blocking.simdgroups: column = "tm_simd_group"
            default: column = "tm_simd_group % \(blocking.blocksN)u"
            }
            statements.append(.line("uint \(registers.columnBlock(0)) = \(column);"))
        }
        for wave in 0..<blocking.waves {
            if registers.sharedColumns {
                let groups = blocking.simdgroups / blocking.blocksN
                // `flat / blocksN` with `flat = simd_group + wave * simdgroups`.
                let base = blocking.blocksN == 1
                    ? "tm_simd_group" : "tm_simd_group / \(blocking.blocksN)u"
                let row = groups == 1
                    ? "\(wave)u"
                    : (wave == 0 ? base : "(\(base) + \(wave * groups)u)")
                if blocking.ragged {
                    statements.append(
                        .line("bool \(registers.live(wave)) = \(row) < \(blocking.blocksM)u;"))
                    statements.append(
                        .line(
                            "uint \(registers.rowBlock(wave)) = "
                                + "\(registers.live(wave)) ? \(row) : 0u;"))
                } else {
                    statements.append(.line("uint \(registers.rowBlock(wave)) = \(row);"))
                }
            } else {
                let flat = "\(registers.prefix)_b\(wave)"
                let index = wave == 0
                    ? "tm_simd_group" : "(tm_simd_group + \(wave * blocking.simdgroups)u)"
                if blocking.ragged {
                    // The tail wave has fewer blocks than simdgroups: the ones with
                    // nothing to do read block 0 (harmless) and skip the store.
                    statements.append(
                        .line("bool \(registers.live(wave)) = \(index) < \(blocking.blocks)u;"))
                    statements.append(
                        .line("uint \(flat) = \(registers.live(wave)) ? \(index) : 0u;"))
                } else {
                    statements.append(.line("uint \(flat) = \(index);"))
                }
                statements.append(
                    .line("uint \(registers.rowBlock(wave)) = \(flat) / \(blocking.blocksN)u;"))
                statements.append(
                    .line("uint \(registers.columnBlock(wave)) = \(flat) % \(blocking.blocksN)u;"))
            }

            var declared: [String] = []
            for row in 0..<blocking.tilesM {
                for column in 0..<blocking.tilesN {
                    let name = registers.register(wave, row, column)
                    declared.append(zeroed ? "\(name) = \(registers.zeroFragment)" : name)
                }
            }
            statements.append(.line("\(registers.matrix) \(declared.joined(separator: ", "));"))
            guard !zeroed else { continue }
            for row in 0..<blocking.tilesM {
                for column in 0..<blocking.tilesN {
                    statements.append(
                        .line(
                            "simdgroup_load(\(registers.register(wave, row, column)), "
                                + "\(origin(registers, wave, row, column)), "
                                + "\(registers.tile.stride)u);"))
                }
            }
        }
        return statements
    }

    /// Writes the register-held fragments back into the accumulator tile, which is
    /// where every downstream per-lane consumer reads the dot's result from.
    private func storeAccumulator(_ registers: AccumulatorRegisters) -> [Stmt] {
        let blocking = registers.blocking
        var statements: [Stmt] = []
        for wave in 0..<blocking.waves {
            var stores: [Stmt] = []
            for row in 0..<blocking.tilesM {
                for column in 0..<blocking.tilesN {
                    stores.append(
                        .line(
                            "simdgroup_store(\(registers.register(wave, row, column)), "
                                + "\(origin(registers, wave, row, column)), "
                                + "\(registers.tile.stride)u);"))
                }
            }
            if blocking.ragged {
                statements.append(
                    .group(open: "if (\(registers.live(wave))) {", body: stores, close: "}"))
            } else {
                statements.append(contentsOf: stores)
            }
        }
        return statements
    }

    /// The contraction loop: one pass over the staged K fragments, reusing each
    /// staged operand fragment across a whole row or column of the register block.
    private func accumulateSteps(
        _ index: Int, _ lhs: Tile, _ rhs: Tile, _ registers: AccumulatorRegisters
    ) -> [Stmt] {
        let size = FunctionEmitter.fragment
        let steps = lhs.paddedColumns / size
        let blocking = registers.blocking
        let operandMatrix =
            lhs.element == .float(width: 16) ? "simdgroup_half8x8" : "simdgroup_float8x8"
        let step = "tm_step\(index)"

        var body: [Stmt] = []
        // One fragment per *distinct address*, not one per use. With the shared
        // column mapping every wave reads the same B fragment, so a step that
        // spells out `waves * (tilesM + tilesN)` loads issues far fewer: at
        // `64x128` on 16 simdgroups, 8 A loads and one B load feed 8
        // multiply-accumulates instead of 16 loads feeding 8.
        var loaded: [String: String] = [:]
        var loads = 0
        /// The variable an address is already in, or `nil` after claiming it.
        func fragment(_ name: String, at address: String) -> String? {
            if let existing = loaded[address] { return existing }
            loaded[address] = name
            loads += 1
            return nil
        }

        for wave in 0..<blocking.waves {
            var a = (0..<blocking.tilesM).map { "tm_a\(index)_\(wave)_\($0)" }
            var b = (0..<blocking.tilesN).map { "tm_b\(index)_\(wave)_\($0)" }
            var declarations: [String] = []
            var loadLines: [Stmt] = []
            for row in 0..<blocking.tilesM {
                let address = "\(lhs.name) + "
                    + "\(registers.fragmentRow(wave, row)) * \(size * lhs.stride)u "
                    + "+ \(step) * \(size)u"
                if let existing = fragment(a[row], at: address) {
                    a[row] = existing
                    continue
                }
                declarations.append(a[row])
                loadLines.append(
                    .line("simdgroup_load(\(a[row]), \(address), \(lhs.stride)u);"))
            }
            for column in 0..<blocking.tilesN {
                let address = "\(rhs.name) + \(step) * \(size * rhs.stride)u + "
                    + "\(registers.fragmentColumn(wave, column)) * \(size)u"
                if let existing = fragment(b[column], at: address) {
                    b[column] = existing
                    continue
                }
                declarations.append(b[column])
                loadLines.append(
                    .line("simdgroup_load(\(b[column]), \(address), \(rhs.stride)u);"))
            }
            if !declarations.isEmpty {
                body.append(.line("\(operandMatrix) \(declarations.joined(separator: ", "));"))
            }
            body.append(contentsOf: loadLines)
            for row in 0..<blocking.tilesM {
                for column in 0..<blocking.tilesN {
                    let target = registers.register(wave, row, column)
                    body.append(
                        .line(
                            "simdgroup_multiply_accumulate(\(target), \(a[row]), \(b[column]), "
                                + "\(target));"))
                }
            }
        }

        let macs = blocking.waves * blocking.tilesM * blocking.tilesN
        return [
            .line(
                "// tt.dot: \(steps) contraction step\(steps == 1 ? "" : "s"), each "
                    + "\(macs) multiply-accumulate\(macs == 1 ? "" : "s") off \(loads) "
                    + "operand load\(loads == 1 ? "" : "s")"),
            .group(
                open: "for (uint \(step) = 0u; \(step) < \(steps)u; ++\(step)) {",
                body: body, close: "}"),
        ]
    }

    /// The address of one accumulator fragment inside its tile.
    private func origin(
        _ registers: AccumulatorRegisters, _ wave: Int, _ row: Int, _ column: Int
    ) -> String {
        let size = FunctionEmitter.fragment
        return "\(registers.tile.name) + \(registers.fragmentRow(wave, row)) * "
            + "\(size * registers.tile.stride)u + "
            + "\(registers.fragmentColumn(wave, column)) * \(size)u"
    }

    // MARK: - Control flow

    /// The nest a whole region has to sit in: deep enough for every value it
    /// reads and every tensor it computes.
    private func regionLevel(_ body: [Instruction], seed: [Int]) -> [Int] {
        var axes = Set(seed)
        func widen(_ ssa: String) { axes.formUnion(layout.path(of: ssa)) }
        for instruction in body {
            switch instruction.kind {
            case .forLoop(let loop):
                for argument in loop.iterArguments {
                    axes.formUnion(levels[argument.initial] ?? [])
                    widen(argument.name)
                }
                axes.formUnion(levels[loop.lowerBound] ?? [])
                axes.formUnion(levels[loop.upperBound] ?? [])
                axes.formUnion(regionLevel(loop.body, seed: []))
            case .ifOp(let branch):
                axes.formUnion(levels[branch.condition] ?? [])
                for (index, type) in branch.resultTypes.enumerated()
                where type.isTensor && index < branch.results.count {
                    widen(branch.results[index])
                }
                axes.formUnion(regionLevel(branch.thenBody, seed: []))
                axes.formUnion(regionLevel(branch.elseBody, seed: []))
            default:
                for operand in instruction.kind.operandNames {
                    axes.formUnion(levels[operand] ?? [])
                }
                if FunctionEmitter.definesTensor(instruction.kind) {
                    for result in instruction.kind.resultNames { widen(result) }
                }
            }
        }
        return axes.sorted()
    }

    /// True when the op materialises a tensor value, which pins it to the
    /// innermost loop even if its operands are program-uniform.
    private static func definesTensor(_ kind: OpKind) -> Bool {
        switch kind {
        case .constant(_, let type, _), .makeRange(_, let type, _, _), .splat(_, let type, _),
            .expandDims(_, let type, _, _), .broadcast(_, let type, _), .cast(_, _, _, let type):
            return type.isTensor
        default:
            return false
        }
    }

    private static func countDots(_ body: [Instruction]) -> Int {
        var total = 0
        for instruction in body {
            switch instruction.kind {
            case .dot: total += 1
            case .forLoop(let loop): total += countDots(loop.body)
            case .ifOp(let branch):
                total += countDots(branch.thenBody) + countDots(branch.elseBody)
            default: break
            }
        }
        return total
    }

    /// Reduction results some `tt.dot` operand depends on.
    ///
    /// A dot operand is rebuilt inside the dot's own staging loops, and a
    /// `tt.reduce` is precisely what cannot be rebuilt there — its fold is
    /// threadgroup-wide and has already happened. Those results are therefore
    /// written into a small threadgroup array where they are computed and read
    /// out of it in the staging loops. This is the second half of what
    /// FlashAttention-2 needs: `p = exp2(qk * scale - m_ij)` is the second dot's
    /// left operand, and `m_ij` is a row reduction.
    static func reductionsReadByADot(in function: TritonFunction, layout: BlockLayout) -> Set<String>
    {
        var definitions: [String: Instruction] = [:]
        var tileBacked: Set<String> = []
        var operands: [String] = []

        func collect(_ body: [Instruction]) {
            for instruction in body {
                for result in instruction.kind.resultNames where definitions[result] == nil {
                    definitions[result] = instruction
                }
                switch instruction.kind {
                case .dot(let dot):
                    tileBacked.insert(dot.result)
                    operands.append(contentsOf: [dot.lhs, dot.rhs, dot.accumulator])
                case .forLoop(let loop):
                    if containsCrossLane(loop.body) {
                        for (index, argument) in loop.iterArguments.enumerated()
                        where argument.type.isTensor {
                            tileBacked.insert(argument.name)
                            if index < loop.results.count { tileBacked.insert(loop.results[index]) }
                        }
                    }
                    collect(loop.body)
                case .ifOp(let branch):
                    collect(branch.thenBody)
                    collect(branch.elseBody)
                default:
                    break
                }
            }
        }
        collect(function.body)

        var spilled: Set<String> = []
        var seen: Set<String> = []
        var stack = operands
        while let value = stack.popLast() {
            guard seen.insert(value).inserted, !tileBacked.contains(value) else { continue }
            // A scalar is program-uniform and already in scope wherever a staging
            // loop needs it, reduction or not.
            guard layout.axes[value] != nil, let instruction = definitions[value] else { continue }
            if case .reduce = instruction.kind {
                spilled.insert(value)
                continue
            }
            stack.append(contentsOf: instruction.kind.operandNames)
        }
        return spilled
    }

    /// True when `body` (or any region inside it) performs a `tt.dot`.
    private static func containsDot(_ body: [Instruction]) -> Bool {
        contains(body) { if case .dot = $0 { return true } else { return false } }
    }

    /// True when `body` (or any region inside it) performs a cross-lane
    /// operation, which decides whether the region has to be lowered
    /// threadgroup-uniformly.
    /// True when `body` contains a reduction, whose fold across the threadgroup
    /// pins the block loops to the innermost-only distribution.
    private static func containsReduce(_ body: [Instruction]) -> Bool {
        contains(body) { if case .reduce = $0 { return true } else { return false } }
    }

    private static func containsCrossLane(_ body: [Instruction]) -> Bool {
        contains(body) {
            switch $0 {
            case .dot, .reduce: return true
            default: return false
            }
        }
    }

    private static func contains(_ body: [Instruction], _ predicate: (OpKind) -> Bool) -> Bool {
        body.contains { instruction in
            if predicate(instruction.kind) { return true }
            switch instruction.kind {
            case .forLoop(let loop): return contains(loop.body, predicate)
            case .ifOp(let branch):
                return contains(branch.thenBody, predicate) || contains(branch.elseBody, predicate)
            default: return false
            }
        }
    }

    private static func terminatorValues(of body: [Instruction]) -> [String] {
        guard case .yield(let values) = body.last?.kind else { return [] }
        return values
    }

    private static func findDefinition(_ ssa: String, in body: [Instruction]) -> Instruction? {
        body.first { $0.kind.resultNames.contains(ssa) }
    }

    private mutating func emitFor(_ loop: ForLoop, loc: SourceLoc) throws {
        if FunctionEmitter.containsCrossLane(loop.body) {
            try emitUniformLoop(loop, loc: loc)
            return
        }
        let level = regionLevel(
            [Instruction(kind: .forLoop(loop), mnemonic: "scf.for", loc: loc)], seed: [])
        try ensureLevel(level, loc)

        guard try type(of: loop.lowerBound, loc).isIntegerLike else {
            throw CoreError.lowering("scf.for bounds must be integers", loc)
        }
        var targets: [YieldTarget] = []
        for argument in loop.iterArguments {
            let initialType = try type(of: argument.initial, loc)
            guard initialType.scalarized == argument.type.scalarized else {
                throw CoreError.lowering(
                    "scf.for iter_arg is \(argument.type) but is initialised from \(initialType)",
                    loc)
            }
            let initialName = try name(of: argument.initial, loc)
            let variable = register(argument.name, type: argument.type)
            levels[argument.name] = level
            try append(
                .line("\(try declaration(argument.type, variable, loc)) = \(initialName);"),
                level: level, recomputable: false,
                reason: "an scf.for's carried values cannot be recomputed", loc)
            targets.append(.variable(variable))
        }

        let induction = register(loop.inductionVariable, type: loop.inductionType)
        levels[loop.inductionVariable] = level
        let inductionName = try scalarTypeName(loop.inductionType, loc)
        let open =
            "for (\(inductionName) \(induction) = \(try name(of: loop.lowerBound, loc)); "
            + "\(induction) < \(try name(of: loop.upperBound, loc)); "
            + "\(induction) += \(try name(of: loop.step, loc))) {"

        frames.append(Frame(path: level, kind: .region, open: open))
        yieldTargets.append(targets)
        for instruction in loop.body { try emit(instruction) }
        yieldTargets.removeLast()
        guard frames[frames.count - 1].kind == .region else {
            throw CoreError.lowering("scf.for body left an unbalanced scope", loc)
        }
        closeTopFrame()
        notRecomputable[level] = "an scf.for's carried values cannot be recomputed"

        for (index, result) in loop.results.enumerated() {
            guard case .variable(let variable) = targets[index] else { continue }
            names[result] = variable
            types[result] = loop.iterArguments[index].type
            levels[result] = level
        }
    }

    /// An `scf.for` whose body performs a cross-lane operation — a `tt.dot` or a
    /// `tt.reduce`.
    ///
    /// Both need every thread of the threadgroup to reach the same barriers, so
    /// the loop is hoisted out of the per-lane block loops entirely and lowered
    /// threadgroup-uniformly; the block loops are then opened and closed *inside*
    /// the body as the cross-lane ops require. That costs the loop its ability to
    /// carry per-lane tensors, so exactly three shapes of `iter_args` are lowered:
    ///
    ///   * **scalars**, which are uniform anyway (a `tt.reduce` result is
    ///     broadcast to every thread) and stay ordinary variables — this is what
    ///     an online softmax carries;
    ///   * a `tt.dot` **accumulator**, which becomes the threadgroup tile the dot
    ///     updates in place, initialised before the loop and read back per lane
    ///     after it; and
    ///   * a **contraction-space pointer** (`a_ptrs += BLOCK_K * stride_ak`),
    ///     which is not carried at all: it is strength-reduced back to
    ///     `init + trip_count * delta` so the dot can rebuild it from scratch.
    ///
    /// Anything else — an ordinary per-lane tensor — is **spilled**: it gets a
    /// threadgroup tile of its own, seeded before the loop, read as a tile
    /// everywhere inside it, and updated once per iteration through a shadow tile
    /// (the new value is written where it is *computed*, because the nest that
    /// computed it is closed by the time `scf.yield` is reached, and the old value
    /// is usually still being read at that point — FlashAttention-2's
    /// `alpha = exp2(m_i - m_ij)` is exactly that). See docs/ARCHITECTURE.md
    /// §Hard parts 3.
    private mutating func emitUniformLoop(_ loop: ForLoop, loc: SourceLoc) throws {
        let level = uniformLevel
        try ensureLevel(level, loc)
        guard try type(of: loop.lowerBound, loc).isIntegerLike else {
            throw CoreError.lowering("scf.for bounds must be integers", loc)
        }
        // The barriers inside make the trip count a threadgroup-wide contract.
        for bound in [loop.lowerBound, loop.upperBound, loop.step] {
            guard FunctionEmitter.isPrefix(levels[bound] ?? [], of: level) else {
                throw CoreError.lowering(
                    "an scf.for containing a cross-lane operation must have a "
                        + "threadgroup-uniform trip count, but its bound '%\(bound)' varies per "
                        + "lane; every thread has to reach the same barriers", loc)
            }
        }

        let yielded = FunctionEmitter.terminatorValues(of: loop.body)
        var targets: [YieldTarget] = []
        var advances: [(argument: String, initial: String, delta: String)] = []
        /// Accumulators this loop holds in registers, to be written back below.
        var resident: [AccumulatorRegisters] = []

        for (index, argument) in loop.iterArguments.enumerated() {
            let yieldValue = index < yielded.count ? yielded[index] : nil

            if isDeferred(argument.name) {
                guard let yieldValue,
                    let update = FunctionEmitter.findDefinition(yieldValue, in: loop.body),
                    case .addPtr(_, let pointer, let offset) = update.kind,
                    pointer == argument.name
                else {
                    throw CoreError.lowering(
                        "'%\(argument.name)' spans a tt.dot's contraction dimension and is carried "
                            + "across this scf.for; only a uniform pointer advance "
                            + "(%next = tt.addptr %arg, %delta) can be rebuilt inside the dot's "
                            + "staging loops", loc)
                }
                let delta = try uniformScalar(offset, in: loop.body, loc)
                targets.append(.deferred)
                advances.append((argument: argument.name, initial: argument.initial, delta: delta))
                continue
            }

            if argument.type.isTensor {
                let dot = yieldValue.flatMap { FunctionEmitter.findDot($0, in: loop.body) }
                // The cheap case, and the one Triton's matmul tutorial writes: the
                // loop yields the dot's result and the dot's accumulator *is* the
                // carried value, so the tile never has to be touched by per-lane
                // code and the fragments can stay in registers for the whole loop.
                guard let dot, dot.accumulator == argument.name else {
                    try spillCarriedTensor(
                        argument, yieldValue: yieldValue, dot: dot, level: level,
                        targets: &targets, loc: loc)
                    continue
                }
                guard case .tensor(let shape, let element) = argument.type, shape.count == 2 else {
                    throw CoreError.lowering(
                        "a tt.dot accumulator must be a rank-2 tensor, found \(argument.type)", loc)
                }
                let accumulatorAxes = layout.axes[argument.name] ?? [0, 1]
                let blocking = self.blocking(rows: shape[0], columns: shape[1])
                let operands = operandArenaSlots(loop.body, blocking: blocking, arena: element)
                let tile = try allocateTile(
                    "dot_c", element: element, rows: shape[0], columns: shape[1],
                    rowAxis: accumulatorAxes[0], columnAxis: accumulatorAxes[1],
                    rowGranularity: blocking.tilesM * FunctionEmitter.fragment,
                    columnGranularity: blocking.tilesN * FunctionEmitter.fragment,
                    capacity: operands, loc)
                let reason = "a tt.dot accumulator cannot be recomputed"
                // The usual `dense<0.0>` seed never goes near threadgroup memory:
                // the fragments start zero in registers, which skips a whole
                // per-lane pass over the tile, one `simdgroup_load` per fragment
                // and both of the barriers that ordered them.
                let zeroed = isZeroSplat(argument.initial)
                if !zeroed {
                    let initial = try stage(argument.initial, into: tile, loc)
                    try append(
                        .line(
                            "// tt.dot accumulator: \(shape[0])x\(shape[1]) in threadgroup memory"),
                        level: level, recomputable: false, reason: reason, loc)
                    try append(initial, level: level, recomputable: false, reason: reason, loc)
                }

                // The accumulator moves into simdgroup registers for the whole
                // loop: initialised once here, updated in place by every `tt.dot`
                // in the body, and written back after the loop closes. Without
                // this each K step reloads and restores every output fragment
                // through threadgroup memory.
                usesSimdgroups = true
                let registers = AccumulatorRegisters(
                    tile: tile, blocking: blocking,
                    matrix: element == .float(width: 16)
                        ? "simdgroup_half8x8" : "simdgroup_float8x8",
                    prefix: "\(tile.name)_r",
                    sharedColumns: FunctionEmitter.sharesColumns(blocking))
                if !zeroed {
                    try append(
                        .line("threadgroup_barrier(mem_flags::mem_threadgroup);"),
                        level: level, recomputable: false, reason: reason, loc)
                }
                for statement in loadAccumulator(registers, zeroed: zeroed) {
                    try append(statement, level: level, recomputable: false, reason: reason, loc)
                }
                // Every simdgroup has its fragments; the tile's storage is now
                // free for the operand tiles to stage into until the loop ends.
                // Nothing read it when the accumulator was born in registers, so
                // there is nothing to order against either.
                if !zeroed {
                    try append(
                        .line("threadgroup_barrier(mem_flags::mem_threadgroup);"),
                        level: level, recomputable: false, reason: reason, loc)
                }
                let capacity = max(tile.elementCount, operands)
                stagingArena = (
                    name: tile.name, element: element, capacity: capacity, cursor: 0
                )
                pingPongTiles = []
                residentAccumulators[tile.name] = registers
                resident.append(registers)

                registerTile(argument.name, tile, type: argument.type)
                targets.append(.tile(tile.name))
                continue
            }

            let initialType = try type(of: argument.initial, loc)
            guard initialType.scalarized == argument.type.scalarized else {
                throw CoreError.lowering(
                    "scf.for iter_arg is \(argument.type) but is initialised from \(initialType)",
                    loc)
            }
            let variable = register(argument.name, type: argument.type)
            levels[argument.name] = level
            try append(
                .line(
                    "\(try declaration(argument.type, variable, loc)) = "
                        + "\(try name(of: argument.initial, loc));"),
                level: level, recomputable: false,
                reason: "an scf.for's carried values cannot be recomputed", loc)
            targets.append(.variable(variable))
        }

        let induction = register(loop.inductionVariable, type: loop.inductionType)
        levels[loop.inductionVariable] = level
        let inductionName = try scalarTypeName(loop.inductionType, loc)
        let lowerBound = try name(of: loop.lowerBound, loc)
        let step = try name(of: loop.step, loc)
        let open =
            "for (\(inductionName) \(induction) = \(lowerBound); "
            + "\(induction) < \(try name(of: loop.upperBound, loc)); "
            + "\(induction) += \(step)) {"

        frames.append(Frame(path: level, kind: .uniformRegion, open: open))
        frames[frames.count - 1].discardable = false

        // The body opens its own block loops, so it gets its own recompute
        // bookkeeping: it inherits the enclosing `history` (a lane loop opened
        // inside the body must rebuild whatever was live when the loops closed
        // around the loop) but must not leak its own statements back out.
        let savedHistory = history
        let savedClosedLevels = closedLevels
        let savedNotRecomputable = notRecomputable
        let savedCanHoist = canHoist
        // Every nest the body might open counts as already closed, so that the
        // first lane loop inside it replays whatever was live when the loops
        // closed around the loop.
        for path in Set(layout.paths.values) where FunctionEmitter.isPrefix(level, of: path) {
            for depth in (level.count + 1)...max(level.count + 1, path.count)
            where depth <= path.count {
                closedLevels.insert(Array(path[0..<depth]))
            }
        }

        // A carried pointer becomes `init + trip_count * delta`, computed once per
        // iteration and rebuilt by the dot from the induction variable.
        for advance in advances {
            let variable = "tm_advance\(advanceCount)"
            let synthetic = "tm$advance\(advanceCount)"
            advanceCount += 1
            frames[frames.count - 1].statements.append(
                .line(
                    "\(inductionName) \(variable) = "
                        + "((\(induction) - \(lowerBound)) / \(step)) * \(advance.delta);"))
            names[synthetic] = variable
            types[synthetic] = loop.inductionType
            levels[synthetic] = level
            valueOrder[synthetic] = nextValueOrder
            nextValueOrder += 1
            definitions[advance.argument] = Instruction(
                kind: .addPtr(
                    result: advance.argument, pointer: advance.initial, offset: synthetic),
                mnemonic: "tt.addptr", loc: loc)
            valueOrder[advance.argument] = nextValueOrder
            nextValueOrder += 1
        }

        let savedSpillCopies = spillCopies
        spillCopies = []
        yieldTargets.append(targets)
        for instruction in loop.body { try emit(instruction) }
        yieldTargets.removeLast()
        try ensureLevel(level, loc)

        // The iteration's new values are all in their shadows; copy them over the
        // carried tiles now that nothing is reading the old ones. Both barriers
        // are load-bearing: the first orders every read of the old value before
        // the overwrite, the second makes the new value visible to the threads
        // that did not write it.
        if !spillCopies.isEmpty {
            let reason = "a spilled loop-carried tensor cannot be recomputed"
            try append(
                .line("// scf.yield: the carried tensors take their new values"),
                level: level, recomputable: false, reason: reason, loc)
            try append(
                .line("threadgroup_barrier(mem_flags::mem_threadgroup);"), level: level,
                recomputable: false, reason: reason, loc)
            for copy in spillCopies where copy.from.name != copy.to.name {
                try append(
                    tileNest(copy.to, [.line("\(copy.to.slot) = \(copy.from.slot);")]),
                    level: level, recomputable: false, sideEffecting: true, poisons: false, loc)
            }
            try append(
                .line("threadgroup_barrier(mem_flags::mem_threadgroup);"), level: level,
                recomputable: false, reason: reason, loc)
            spillCopies = []
        }
        spillCopies = savedSpillCopies

        guard frames[frames.count - 1].kind == .uniformRegion else {
            throw CoreError.lowering("scf.for body left an unbalanced scope", loc)
        }
        if !pingPongTiles.isEmpty {
            frames[frames.count - 1].statements.append(
                .line("// tt.dot: the next step stages into the other half of the arena"))
            for tile in pingPongTiles {
                frames[frames.count - 1].statements.append(
                    .line(
                        "{ threadgroup \(tile.element) *tm_swap = \(tile.name); "
                            + "\(tile.name) = \(tile.name)_next; \(tile.name)_next = tm_swap; }"))
            }
            pingPongTiles = []
        }
        closeTopFrame()

        // The contraction is over: put the register-held accumulators back in
        // their tiles, where every per-lane consumer downstream reads them from.
        stagingArena = nil
        for registers in resident {
            let reason = "a tt.dot accumulator cannot be recomputed"
            try append(
                .line("// tt.dot accumulator: back to threadgroup memory for the epilogue"),
                level: level, recomputable: false, reason: reason, loc)
            // The operand tiles alias the storage about to be written, so every
            // simdgroup has to be finished reading them first.
            try append(
                .line("threadgroup_barrier(mem_flags::mem_threadgroup);"),
                level: level, recomputable: false, reason: reason, loc)
            for statement in storeAccumulator(registers) {
                try append(statement, level: level, recomputable: false, reason: reason, loc)
            }
            try append(
                .line("threadgroup_barrier(mem_flags::mem_threadgroup);"),
                level: level, recomputable: false, reason: reason, loc)
            residentAccumulators[registers.tile.name] = nil
        }

        history = savedHistory
        closedLevels = savedClosedLevels
        notRecomputable = savedNotRecomputable
        canHoist = savedCanHoist
        notRecomputable[level] =
            "an scf.for containing a cross-lane operation cannot be recomputed"

        for (index, result) in loop.results.enumerated() {
            switch targets[index] {
            case .variable(let variable):
                names[result] = variable
                types[result] = loop.iterArguments[index].type
                levels[result] = level
            case .tile, .spilled:
                registerTile(
                    result, tiles[loop.iterArguments[index].name]!,
                    type: loop.iterArguments[index].type)
            case .deferred:
                continue
            }
        }
    }

    /// A per-lane tensor carried across a cross-lane loop, spilled to a tile.
    ///
    /// Two shapes. When the loop yields a `tt.dot`'s **result** but the dot's
    /// accumulator is some per-lane function of the carried value rather than the
    /// carried value itself — FlashAttention-2's
    /// `acc = tt.dot(p, v, acc * alpha[:, None])` — the carried tile *is* the
    /// dot's accumulator tile and that function is lowered as the staging pass
    /// that fills it. Each staging thread reads and writes the same element, so
    /// the rescale needs no ordering staging does not already have, there is no
    /// copy, and the tile exists once.
    ///
    /// Otherwise the value gets a tile and a shadow. The new value is written
    /// into the shadow where it is *defined*, because by `scf.yield` the nest that
    /// computed it has been closed (a `tt.reduce` result cannot be rebuilt) and
    /// because the old value is usually still being read at that point; the shadow
    /// is copied over the tile once, at the end of the body, between barriers.
    private mutating func spillCarriedTensor(
        _ argument: (name: String, initial: String, type: TMType), yieldValue: String?,
        dot: DotOp?, level: [Int], targets: inout [YieldTarget], loc: SourceLoc
    ) throws {
        guard case .tensor(let shape, let element) = argument.type else {
            throw CoreError.lowering("scf.for carries a non-tensor as a tensor", loc)
        }
        let path = layout.path(of: argument.name)
        guard !path.isEmpty, path.count <= 2 else {
            throw CoreError.lowering(
                "scf.for carries '%\(argument.name)' across a cross-lane operation, but it spans "
                    + "\(path.count) block dimensions; only rank-1 and rank-2 carried tensors are "
                    + "spilled into threadgroup memory", loc)
        }
        let reason = "a spilled loop-carried tensor cannot be recomputed"

        if let dot, yieldValue == dot.result {
            guard shape.count == 2, let axes = layout.axes[argument.name], axes.count == 2 else {
                throw CoreError.lowering(
                    "a tt.dot accumulator must be a rank-2 tensor, found \(argument.type)", loc)
            }
            let blocking = self.blocking(rows: shape[0], columns: shape[1])
            let tile = try allocateTile(
                "dot_c", element: element, rows: shape[0], columns: shape[1],
                rowAxis: axes[0], columnAxis: axes[1],
                rowGranularity: blocking.tilesM * FunctionEmitter.fragment,
                columnGranularity: blocking.tilesN * FunctionEmitter.fragment, loc)
            try append(
                .line(
                    "// scf.for carries a \(shape[0])x\(shape[1]) tt.dot accumulator that is "
                        + "rescaled per iteration; it stays in threadgroup memory"),
                level: level, recomputable: false, reason: reason, loc)
            try seedTile(tile, from: argument.initial, at: level, loc)
            hasSpilledTiles = true
            registerTile(argument.name, tile, type: argument.type)
            boundAccumulators[dot.result] = tile
            targets.append(.tile(tile.name))
            return
        }

        let tile = try spillTile("carry", for: argument.name, type: argument.type, loc)
        try append(
            .line(
                "// scf.for carries '%\(argument.name)' across a cross-lane operation: spilled to "
                    + "threadgroup memory, updated through a shadow tile"),
            level: level, recomputable: false, reason: reason, loc)
        try seedTile(tile, from: argument.initial, at: level, loc)
        registerTile(argument.name, tile, type: argument.type)

        guard let yieldValue, yieldValue != argument.name else {
            targets.append(.tile(tile.name))
            return
        }
        let shadow = try spillTile("carry_next", for: argument.name, type: argument.type, loc)
        shadowWrites[yieldValue] = shadow
        targets.append(.spilled(tile: tile, shadow: shadow, value: yieldValue))
    }

    /// A self-contained loop nest over one tile's own extents, spread over the
    /// whole threadgroup.
    ///
    /// Deliberately *not* built with `ensureLevel`: a tile copy reads and writes
    /// threadgroup memory and needs none of the per-lane values the block loops
    /// exist to rebuild, so it must not be blocked by a nest that a `tt.reduce`
    /// has made unrecomputable — which, inside an online softmax's loop, is every
    /// nest there is.
    private func tileNest(_ tile: Tile, _ body: [Stmt]) -> Stmt {
        let threads = threadsPerThreadgroup
        let row = "tm_i\(tile.rowAxis)"
        guard tile.hasColumns, tile.columns > 1 else {
            return .group(
                open: "for (uint \(row) = tm_thread_id.x; \(row) < \(max(1, tile.rows))u; "
                    + "\(row) += \(threads)u) {", body: body, close: "}")
        }
        var lanes = 1
        while lanes * 2 <= min(tile.columns, threads), threads % (lanes * 2) == 0 { lanes *= 2 }
        let column = "tm_i\(tile.columnAxis)"
        let inner = Stmt.group(
            open: "for (uint \(column) = tm_thread_id.x % \(lanes)u; "
                + "\(column) < \(tile.columns)u; \(column) += \(lanes)u) {", body: body, close: "}")
        return .group(
            open: "for (uint \(row) = tm_thread_id.x / \(lanes)u; \(row) < \(tile.rows)u; "
                + "\(row) += \(max(1, threads / lanes))u) {", body: [inner], close: "}")
    }

    /// Fills a carried tile with its `iter_args` initialiser, padding included.
    ///
    /// The flat pass is what covers the fragment padding, which no per-lane nest
    /// walks and which a `simdgroup_load` of an edge fragment still reads.
    private mutating func seedTile(
        _ tile: Tile, from initial: String, at level: [Int], _ loc: SourceLoc
    ) throws {
        let reason = "a spilled loop-carried tensor cannot be recomputed"
        var splat: String? = nil
        if let instruction = definitions[initial], case .constant(_, let type, let value) = instruction.kind {
            splat = literal(value, type.withElement(tile.element), loc)
        }
        let fill = splat ?? literal(
            tile.element.isFloatLike ? .float(0) : .integer(0), tile.element, loc)
        try append(
            .line(
                "for (uint tm_seed = tm_thread_id.x; tm_seed < \(tile.elementCount)u; "
                    + "tm_seed += tm_threadgroup_size.x) { \(tile.name)[tm_seed] = \(fill); }"),
            level: level, recomputable: false, sideEffecting: true, poisons: false, loc)
        if splat == nil {
            guard (levels[initial] ?? []).isEmpty else {
                throw CoreError.lowering(
                    "the initial value of the carried tensor in '\(tile.name)' is itself a "
                        + "per-lane tensor computed inside the block loops; a cross-lane loop can "
                        + "only be seeded from a splat or a program-uniform value", loc)
            }
            try append(
                tileNest(tile, [.line("\(tile.slot) = \(try name(of: initial, loc));")]),
                level: level, recomputable: false, sideEffecting: true, poisons: false, loc)
        }
        try append(
            .line("threadgroup_barrier(mem_flags::mem_threadgroup);"), level: level,
            recomputable: false, reason: reason, loc)
    }

    private static func findDot(_ result: String, in body: [Instruction]) -> DotOp? {
        for instruction in body {
            if case .dot(let dot) = instruction.kind, dot.result == result { return dot }
        }
        return nil
    }

    /// Resolves a `tt.dot` pointer advance to a threadgroup-uniform scalar,
    /// looking through the `tt.splat` Triton wraps it in.
    private func uniformScalar(_ ssa: String, in body: [Instruction], _ loc: SourceLoc) throws
        -> String
    {
        if let expression = uniformExpression(ssa, in: body, depth: 0, loc) { return expression }
        throw CoreError.lowering(
            "the pointer advance '%\(ssa)' inside a tt.dot loop is not uniform across the "
                + "threadgroup; it has to be a splat of a value computed outside the loop", loc)
    }

    /// Resolves `ssa` to a threadgroup-uniform MSL scalar expression, or nil.
    ///
    /// Three shapes turn up in real Triton output for the same source-level
    /// `ptrs += BLOCK_K * stride`: a `tt.splat` of a scalar the loop hoisted out,
    /// a dense splat constant the canonicalizer folded (`dense<16> : tensor<64x16xi32>`),
    /// and — when the stride is a kernel argument — the scalar product recomputed
    /// *inside* the loop body, whose operands are still loop-invariant. All three
    /// name one value per threadgroup, which is all the staging loops need.
    private func uniformExpression(_ ssa: String, in body: [Instruction], depth: Int, _ loc: SourceLoc)
        -> String?
    {
        if depth > 8 { return nil }
        if let name = names[ssa], (levels[ssa] ?? []).isEmpty, tiles[ssa] == nil {
            return name
        }
        guard let instruction = definitions[ssa] ?? FunctionEmitter.findDefinition(ssa, in: body)
        else { return nil }
        switch instruction.kind {
        case .constant(_, let type, let value):
            return literal(value, type, loc)
        case .splat(_, _, let source):
            return uniformExpression(source, in: body, depth: depth + 1, loc)
        case .intBinary(_, let op, let lhs, let rhs):
            guard let symbol = FunctionEmitter.uniformIntOperator(op),
                let l = uniformExpression(lhs, in: body, depth: depth + 1, loc),
                let r = uniformExpression(rhs, in: body, depth: depth + 1, loc)
            else { return nil }
            return "(\(l) \(symbol) \(r))"
        default:
            return nil
        }
    }

    /// The signed integer operators that mean the same thing in MSL, spelled
    /// inline. Anything needing a cast (unsigned, min/max) is left to the general
    /// path, which refuses rather than guessing.
    private static func uniformIntOperator(_ op: IntBinaryOp) -> String? {
        switch op {
        case .add: return "+"
        case .sub: return "-"
        case .mul: return "*"
        case .divs: return "/"
        case .rems: return "%"
        case .shl: return "<<"
        case .shrs: return ">>"
        default: return nil
        }
    }

    private mutating func emitIf(_ branch: IfOp, loc: SourceLoc) throws {
        guard !FunctionEmitter.containsDot(branch.thenBody),
            !FunctionEmitter.containsDot(branch.elseBody)
        else {
            throw CoreError.lowering(
                "tt.dot inside an scf.if is not lowered: its threadgroup barriers would only be "
                    + "reached by the threads taking that branch", loc)
        }
        let level = regionLevel(
            [Instruction(kind: .ifOp(branch), mnemonic: "scf.if", loc: loc)], seed: [])
        try ensureLevel(level, loc)

        let conditionType = try type(of: branch.condition, loc)
        guard conditionType.scalarized == .integer(width: 1) else {
            throw CoreError.lowering(
                "scf.if condition must be i1, found \(conditionType)", loc)
        }

        let conditionName = try name(of: branch.condition, loc)
        var targets: [YieldTarget] = []
        for (index, resultType) in branch.resultTypes.enumerated() {
            let variable = register(branch.results[index], type: resultType)
            levels[branch.results[index]] = level
            try append(
                .line("\(try declaration(resultType, variable, loc));"), level: level,
                recomputable: false, reason: "an scf.if's results cannot be recomputed", loc)
            targets.append(.variable(variable))
        }
        guard branch.resultTypes.isEmpty || !branch.elseBody.isEmpty else {
            throw CoreError.lowering("scf.if with results needs an else region", loc)
        }

        for (isThen, body) in [(true, branch.thenBody), (false, branch.elseBody)] {
            if !isThen && body.isEmpty { continue }
            let open = isThen ? "if (\(conditionName)) {" : "else {"
            frames.append(Frame(path: level, kind: .region, open: open))
            yieldTargets.append(targets)
            for instruction in body { try emit(instruction) }
            yieldTargets.removeLast()
            closeTopFrame()
        }
        notRecomputable[level] = "an scf.if's results cannot be recomputed"
    }

    // MARK: - Checks and literals

    private func binaryOperandType(
        _ lhs: String, _ rhs: String, _ op: String, _ loc: SourceLoc
    ) throws -> TMType {
        let l = try type(of: lhs, loc)
        let r = try type(of: rhs, loc)
        guard l == r else {
            throw CoreError.lowering("\(op) operand types differ: \(l) vs \(r)", loc)
        }
        return l
    }

    private func checkShape(
        _ mask: String, against pointerType: TMType, _ what: String, _ loc: SourceLoc
    ) throws {
        let maskType = try type(of: mask, loc)
        guard maskType.scalarized == .integer(width: 1) else {
            throw CoreError.lowering("\(what) must be i1, found \(maskType)", loc)
        }
        guard maskType.shape == pointerType.shape else {
            throw CoreError.lowering(
                "\(what) shape \(maskType) does not match pointer shape \(pointerType)", loc)
        }
    }

    private func literal(_ value: ConstantValue, _ type: TMType, _ loc: SourceLoc) -> String {
        switch (value, type.scalarized) {
        case (.integer(let v), .integer(let width)):
            if width == 1 { return v != 0 ? "true" : "false" }
            return "\(v)"
        case (.integer(let v), .float(let width)):
            return floatLiteral(Double(v), width: width)
        case (.float(let v), .float(let width)):
            return floatLiteral(v, width: width)
        case (.float(let v), .integer):
            return "\(Int64(v))"
        default:
            return "0"
        }
    }

    private func floatLiteral(_ value: Double, width: Int) -> String {
        let suffix = width == 16 ? "h" : "f"
        if value.isNaN { return "NAN" }
        if value.isInfinite { return value < 0 ? "-INFINITY" : "INFINITY" }
        var text = "\(value)"
        if !text.contains(".") && !text.contains("e") && !text.contains("E") {
            text += ".0"
        }
        return text + suffix
    }
}

extension TMType {
    /// `tensor<MxNxT>` -> `tensor<MxT>`, `tensor<NxT>` -> `T`.
    func reducingLastDimension() -> TMType {
        guard case .tensor(var shape, let element) = self, !shape.isEmpty else { return self }
        shape.removeLast()
        return shape.isEmpty ? element : .tensor(shape: shape, element: element)
    }
}
